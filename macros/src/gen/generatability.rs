/// Which generator is asking. A PARAMETER of [`generatability`], never a second copy of it.
///
/// ⚠ [`Self::RandomTerm`] and [`Self::ExhaustiveTerm`] route to the same classifier because they
/// are MEASURED co-extensional over the corpus today, not because they are assumed to be:
/// `term_gen/exhaustive.rs` has no counterpart to `random.rs:418`'s collection-arity gate, yet it
/// drops the identical fifteen Rholang rules (verified against
/// `target/generated/rholang/{random,term}_generation.rs`). They are kept as separate
/// discriminants so that a future divergence must be spelled as a second arm, and the census's
/// matrix will demand it.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub(crate) enum Generator {
    /// `test_gen/strategies.rs` — the proptest tape builder (`arb_<cat>`).
    TapeBuilder,
    /// `test_gen/unit_tests.rs` — the static per-constructor unit test.
    UnitTest,
    /// `term_gen/random.rs` — `generate_random_at_depth`.
    RandomTerm,
    /// `term_gen/exhaustive.rs` — `generate_terms_at_depth`.
    ExhaustiveTerm,
}

impl Generator {
    /// Every generator, so the census cannot range over a subset by omission.
    pub(crate) const ALL: [Generator; 4] =
        [Self::TapeBuilder, Self::UnitTest, Self::RandomTerm, Self::ExhaustiveTerm];

    /// The stable, assertable spelling.
    pub(crate) const fn as_str(self) -> &'static str {
        match self {
            Self::TapeBuilder => "TapeBuilder",
            Self::UnitTest => "UnitTest",
            Self::RandomTerm => "RandomTerm",
            Self::ExhaustiveTerm => "ExhaustiveTerm",
        }
    }
}

/// WHY a generator cannot build a rule. TOTAL over the reasons, with **no wildcard**, so a new
/// refusal must be classified here before it can be spelled anywhere.
///
/// Each variant names a concrete, independently checkable defect — never a spelling, a name
/// prefix, or a line number. `THE KEY IS THE CAUSE, NEVER A SPELLING`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub(crate) enum GeneratorGap {
    /// The rule's surface begins with a `__`-prefixed internal terminal, so a generated term's
    /// `Display` is not re-parseable. `strategies.rs:331`. ★ PORTED, not deleted — see the module
    /// header's falsifier.
    InternalSurface,
    /// A GUEST-BODY field (`*flt(…)` → `Arc<FltNode>`) has no tape construction and no reliably
    /// re-parseable `Display`. `strategies.rs:490`.
    GuestBodyLeaf,
    /// A `v@Tok` token-kind capture beside a category child: the text must satisfy a DECLARED
    /// kind's lexer pattern that this builder has no handle on. `strategies.rs:507`.
    DeclaredTokenKindCapture,
    /// No field references a declared category (or there are no fields), so there is nothing to
    /// recurse into and no leaf treatment applies. `strategies.rs:570`.
    NoRecursiveField,
    /// A field recurses into a RUNTIME-ONLY opaque native (`z:ReadZipper`), fillable only by an
    /// unparseable arb leaf. `strategies.rs:584`.
    RuntimeOnlyNativeField,
    /// A `Collection`/`Binder`/`MultiBinder` element or body category is not declared in
    /// `language.types`. `strategies.rs:595`/`:609`/`:625`.
    UnknownCategory,
    /// Some field has no STATIC leaf value, so a unit test cannot construct the term without
    /// recursion. `unit_tests.rs`, the `Regular`/`Binder` arms.
    NoStaticLeafForField,
    /// A collection constructor needs non-trivial element setup the static emitter does not do.
    /// `unit_tests.rs`, the `Collection` arm.
    CollectionElementSetup,
    /// A multi-binder needs a `Vec<Binder>` the static emitter does not build.
    /// `unit_tests.rs`, the `MultiBinder` arm.
    MultiBinderVecBinder,
    /// A Class-2 binder rule (more than one `Simple` term param) whose slot list also holds a
    /// collection: wider arity than the single-arg container the collection-constructor codegen
    /// assumes. `random.rs:418`.
    Class2CollectionArity,
    /// An `Optional` term param beside a collection — same arity mismatch, different cause, so a
    /// different discriminant. `random.rs:418`.
    OptionalCollectionArity,
    /// A MultiAbstraction rule that also carries a collection: `Collection`+`MultiBinder` codegen
    /// does not exist. `random.rs:377`.
    MultiBinderWithCollection,
    /// A TOP-LEVEL (mandatory) `?guard:Guard` slot requires generating a predicate, which the
    /// term_gen pipeline does not do. `random.rs:470`, `exhaustive.rs:769`.
    MandatoryGuardSlot,
}

impl GeneratorGap {
    /// The stable, assertable spelling.
    pub(crate) const fn as_str(self) -> &'static str {
        match self {
            Self::InternalSurface => "InternalSurface",
            Self::GuestBodyLeaf => "GuestBodyLeaf",
            Self::DeclaredTokenKindCapture => "DeclaredTokenKindCapture",
            Self::NoRecursiveField => "NoRecursiveField",
            Self::RuntimeOnlyNativeField => "RuntimeOnlyNativeField",
            Self::UnknownCategory => "UnknownCategory",
            Self::NoStaticLeafForField => "NoStaticLeafForField",
            Self::CollectionElementSetup => "CollectionElementSetup",
            Self::MultiBinderVecBinder => "MultiBinderVecBinder",
            Self::Class2CollectionArity => "Class2CollectionArity",
            Self::OptionalCollectionArity => "OptionalCollectionArity",
            Self::MultiBinderWithCollection => "MultiBinderWithCollection",
            Self::MandatoryGuardSlot => "MandatoryGuardSlot",
        }
    }
}

/// The verdict. Two inhabitants, and the refusing one CARRIES ITS REASON — which is the whole
/// difference between this and the `continue` it replaces: *a disposition is a value, not an
/// absence*.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Generatability {
    /// This generator can build a term for the rule.
    Buildable,
    /// It cannot, for the named reason.
    Refused(GeneratorGap),
}

impl Generatability {
    /// The gap, when refused.
    pub(crate) const fn gap(self) -> Option<GeneratorGap> {
        match self {
            Self::Buildable => None,
            Self::Refused(gap) => Some(gap),
        }
    }
}

