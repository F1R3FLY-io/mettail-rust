fn has_collection_item(rule: &GrammarRule) -> bool {
    rule.items
        .iter()
        .any(|item| matches!(item, GrammarItem::Collection { .. }))
}

/// `random.rs:377` — a MultiAbstraction rule the multi-binder arm cannot serve.
pub(crate) fn term_multi_binder_gap(rule: &GrammarRule) -> Option<GeneratorGap> {
    let is_multi_binder = rule.term_context.as_ref().is_some_and(|ctx| {
        ctx.iter()
            .any(|p| matches!(p, TermParam::MultiAbstraction { .. }))
    });
    if !is_multi_binder {
        return None;
    }
    (rule.bindings.is_empty() || has_collection_item(rule))
        .then_some(GeneratorGap::MultiBinderWithCollection)
}

/// `random.rs:418` — ONE `continue` in the source carrying TWO causes.
///
/// The two get separate discriminants because a row keyed on the SITE could not tell a reader
/// which defect to fix: a Class-2 binder rule needs a Class-2 collection generator, an
/// `Optional`-param rule needs the optional-arity split. That is `collection_carrier`'s arity
/// lesson — *two outcomes cannot express three carriers* — applied one level down.
pub(crate) fn term_collection_arity_gap(rule: &GrammarRule) -> Option<GeneratorGap> {
    if !has_collection_item(rule) {
        return None;
    }
    let ctx = rule.term_context.as_ref();
    if ctx.is_some_and(|ctx| {
        ctx.iter()
            .filter(|p| matches!(p, TermParam::Simple { .. }))
            .count()
            > 1
    }) {
        return Some(GeneratorGap::Class2CollectionArity);
    }
    if ctx.is_some_and(|ctx| ctx.iter().any(|p| matches!(p, TermParam::Optional { .. }))) {
        return Some(GeneratorGap::OptionalCollectionArity);
    }
    None
}

/// `random.rs:470` / `exhaustive.rs:769` — a TOP-LEVEL (mandatory) `?guard:Guard` slot.
///
/// The top-level-only scan is INTENTIONAL: a guard inside `#opt(...)` is generatable (as `None`,
/// via the Optional count split), so `Optional { GuardBody }` must NOT trip this.
pub(crate) fn term_guard_slot_gap(rule: &GrammarRule) -> Option<GeneratorGap> {
    rule.term_context
        .as_ref()
        .is_some_and(|ctx| ctx.iter().any(|p| matches!(p, TermParam::GuardBody { .. })))
        .then_some(GeneratorGap::MandatoryGuardSlot)
}

/// Whether a random / exhaustive term generator can build this rule at depth > 0.
///
/// ⚠ **THE COMPOSITION ORDER IS `random.rs`'s OWN, and it is load-bearing.** The generator
/// applies its gates in this sequence:
///
/// ```text
///   :360  is_multi_binder      ─▶ push a multi-binder case, or continue
///   :410  has_collections && !class2 && !optional ─▶ push a COLLECTION constructor, continue
///   :418  has_collections && (class2 || optional) ─▶ continue
///   :433  non_terminals.is_empty()               ─▶ continue   (dispatch to depth 0)
///   :446  single builtin non-terminal            ─▶ continue   (dispatch to depth 0)
///   :470  has_guard_slot                         ─▶ continue
/// ```
///
/// So a rule with BOTH a collection and a guard slot is PUSHED at `:410` and never reaches the
/// guard check — it is buildable. Composing guard-first (the first draft of this function did)
/// would have reported a gap for a rule the generator generates perfectly well, and the
/// byte-identity control would have caught it as a diff in generated output. The order below
/// mirrors the generator exactly, and the generator calls these same three functions at these
/// same three positions.
///
/// `exhaustive.rs` applies the guard gate earlier and has no counterpart to `:418`; the two are
/// nevertheless MEASURED co-extensional on the corpus (see [`Generator`]), and the census's
/// matrix is what would report a divergence.
pub(crate) fn term_rule_gap(rule: &GrammarRule) -> Option<GeneratorGap> {
    if let Some(gap) = term_multi_binder_gap(rule) {
        return Some(gap);
    }
    if has_collection_item(rule) {
        // `:410`/`:418` — either an arity gap, or a pushed collection constructor. Nothing
        // further applies: the generator `continue`s in both cases.
        return term_collection_arity_gap(rule);
    }
    if is_depth_zero_shape(rule) {
        return None;
    }
    term_guard_slot_gap(rule)
}

/// Whether `rule` has no category/binder child at all, i.e. it is a depth-0 shape served by the
/// nullary/var/literal walk rather than dropped.
///
/// Exposed so the census can EXCLUDE depth-0 rules from the term-generator domain instead of
/// reporting them as gaps: `generate_random_depth_gt_0`'s `non_terminals.is_empty()` `continue`
/// is a dispatch, not a refusal, and counting it would inflate the gap set with rules that are
/// generated perfectly well one arm over.
pub(crate) fn is_depth_zero_shape(rule: &GrammarRule) -> bool {
    let non_terminals = rule
        .items
        .iter()
        .filter(|item| matches!(item, GrammarItem::NonTerminal { .. } | GrammarItem::Binder { .. }))
        .count();
    if non_terminals == 0 {
        return true;
    }
    if non_terminals == 1 {
        if let Some(kind) = rule.items.iter().find_map(|item| match item {
            GrammarItem::NonTerminal { kind, .. } => Some(*kind),
            _ => None,
        }) {
            return kind.is_builtin() || kind == mettail_ast::grammar::NonTerminalKind::Var;
        }
    }
    false
}

