/// RULE-level tape gate: an internal-only `__`-prefixed surface.
///
/// Checks the FIRST literal in the syntax pattern, so a param-led rule whose first terminal is
/// `__…` is also covered; a rule with no literal (a pure cast) is not internal.
///
/// ★ This is `strategies.rs`'s former `rule_has_internal_surface`, moved rather than copied. Its
/// two live subjects are Rholang's `GuardThen` (`__guard_then`) and `CommWhere` (`__comm_where`).
/// A third, `PParInternal` (`__ppar`), was deleted from the grammar on 2026-07-29 and was the one
/// rule that falsified the accompanying *"they still PARSE"* clause: measured before deletion,
/// `__ppar(Nil, Nil)` did not parse at all. Do not extend that clause to a new `__` rule without
/// measuring.
pub(crate) fn tape_rule_gap(rule: &GrammarRule) -> Option<GeneratorGap> {
    let internal = rule
        .syntax_pattern
        .as_ref()
        .and_then(|sp| {
            sp.iter().find_map(|e| match e {
                SyntaxExpr::Literal(s) => Some(s.starts_with("__")),
                _ => None,
            })
        })
        .unwrap_or(false);
    internal.then_some(GeneratorGap::InternalSurface)
}

fn is_guest_body(field: &FieldInfo) -> bool {
    field.opaque_leaf == Some(OpaqueLeafKind::GuestBody)
}

fn is_token_text(field: &FieldInfo) -> bool {
    field.opaque_leaf == Some(OpaqueLeafKind::TokenText)
}

/// VARIANT-level tape gate — the seven `continue`s of `classify_variants`, in the order the
/// generator applied them.
///
/// ⚠ **THE ORDER IS LOAD-BEARING AND ONE STEP IS A `None`.** Between `:507` and `:570` sat a
/// branch that is not a skip at all: a variant whose fields are ALL token-text leaves with a
/// matching `m:Ident` param count is a **buildable LEAF**, and its condition IMPLIES `:570`'s
/// (`!has_recursive_field`). Hoisting the skips above it without that early `Buildable` would
/// silently drop every such variant — so the buildable case is returned explicitly here rather
/// than left to fall through.
pub(crate) fn tape_variant_gap(
    variant: &VariantKind,
    category: &str,
    language: &LanguageDef,
) -> Option<GeneratorGap> {
    let known = |cat: &syn::Ident| language.types.iter().any(|t| t.name == *cat);
    match variant {
        VariantKind::Regular { label, fields } => {
            let has_recursive_field = fields.iter().any(|f| known(&f.category));
            let ident_params = ident_param_count_for(category, &label.to_string(), language);

            // :490 — a guest body has no tape construction and no re-parseable Display.
            if fields.iter().any(is_guest_body) {
                return Some(GeneratorGap::GuestBodyLeaf);
            }
            // :507 — a `v@Tok` capture beside a category child.
            if has_recursive_field && fields.iter().any(is_token_text) && ident_params == 0 {
                return Some(GeneratorGap::DeclaredTokenKindCapture);
            }
            // ★ NOT A SKIP — the all-token-text LEAF is BUILDABLE, and must be answered before
            // `:570`, whose condition it implies. `ident_samples` walks the language's effective
            // `Ident` pattern, which governs `m:Ident` params and NOT `v@Tok` captures of a
            // declared kind, so the count equality is POSITIVE evidence of the former.
            if !fields.is_empty()
                && !has_recursive_field
                && fields.iter().all(is_token_text)
                && ident_params == fields.len()
            {
                return None;
            }
            // :570 — nothing to recurse into.
            if !has_recursive_field || fields.is_empty() {
                return Some(GeneratorGap::NoRecursiveField);
            }
            // :584 — a runtime-only opaque native field.
            if fields
                .iter()
                .any(|f| crate::gen::category_is_runtime_only_native(&f.category, language))
            {
                return Some(GeneratorGap::RuntimeOnlyNativeField);
            }
            None
        },
        // :595 — a collection whose element category is not declared.
        VariantKind::Collection { element_cat, .. } => {
            (!known(element_cat)).then_some(GeneratorGap::UnknownCategory)
        },
        // :609 / :625 — a binder whose body category is not declared.
        VariantKind::Binder { body_cat, .. } | VariantKind::MultiBinder { body_cat, .. } => {
            (!known(body_cat)).then_some(GeneratorGap::UnknownCategory)
        },
        // A nullary / literal / var / collection-literal / refused variant is never dropped by
        // this walk: `Refused` deliberately KEEPS its arm and emits a `compile_error!` body
        // (#141 G5), which is a diagnostic rather than a gap.
        VariantKind::Nullary { .. }
        | VariantKind::Literal { .. }
        | VariantKind::CollectionLiteral { .. }
        | VariantKind::Var { .. }
        | VariantKind::Refused { .. } => None,
    }
}

/// How many builtin `m:Ident` params the rule named `(category, label)` declares.
///
/// The tape builder reads `FieldInfo::opaque_leaf`, which cannot tell an `m:Ident` param from a
/// `v@Tok` capture of a declared kind — and the two are governed by different lexer patterns.
/// This reaches back to the RULE for that distinction. Returns 0 when no such rule exists (a
/// synthesized variant has no term context).
fn ident_param_count_for(category: &str, label: &str, language: &LanguageDef) -> usize {
    language
        .terms
        .iter()
        .find(|r| r.category == *category && r.label == *label)
        .map_or(0, crate::gen::term_gen::ident_param_count)
}

