/// Whether the static unit-test emitter can construct this variant from leaf values alone.
///
/// The `Regular` / `Binder` answer is `construct_leaf_value`'s: if ANY field has no static leaf,
/// the whole constructor is refused. `Collection` and `MultiBinder` are refused unconditionally —
/// and that unconditionality is now a NAMED gap rather than an `always None` arm, which is what
/// makes them countable.
pub(crate) fn unit_variant_gap(
    variant: &VariantKind,
    language: &LanguageDef,
) -> Option<GeneratorGap> {
    let no_leaf = |fields: &[FieldInfo]| {
        fields
            .iter()
            .any(|f| crate::gen::test_gen::unit_tests::construct_leaf_value(f, language).is_none())
    };
    match variant {
        VariantKind::Regular { fields, .. } => {
            no_leaf(fields).then_some(GeneratorGap::NoStaticLeafForField)
        },
        VariantKind::Binder { pre_scope_fields, .. } => {
            no_leaf(pre_scope_fields).then_some(GeneratorGap::NoStaticLeafForField)
        },
        VariantKind::Collection { .. } => Some(GeneratorGap::CollectionElementSetup),
        VariantKind::MultiBinder { .. } => Some(GeneratorGap::MultiBinderVecBinder),
        VariantKind::Nullary { .. }
        | VariantKind::Literal { .. }
        | VariantKind::CollectionLiteral { .. }
        | VariantKind::Var { .. }
        | VariantKind::Refused { .. } => None,
    }
}

