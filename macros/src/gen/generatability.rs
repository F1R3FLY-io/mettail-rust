//! **#150 — THE single classification of "can a generator build a term for this rule?".**
//!
//! # What was wrong, and what "one predicate" has to mean
//!
//! Three generators each decided, inline and silently, that they could not build a declared rule:
//!
//! | generator | site | skip form |
//! |---|---|---|
//! | tape builder | `test_gen/strategies.rs` — `collect_spec_only_variants` + `classify_variants` | 8 bare `continue`s |
//! | unit tests | `test_gen/unit_tests.rs` — four `VariantKind` arms | `None`, traced only by a COMMENT in generated output |
//! | random / exhaustive term | `term_gen/random.rs` + `term_gen/exhaustive.rs` | bare `continue` / `quote! {}`, **no trace at all** |
//!
//! ★★ **The filing's framing needed one correction, and it is the load-bearing part of this
//! module.** It reads *"3 mutually-disagreeing predicates"*, which implies they ought to agree.
//! **They ought not.** They answer three different questions:
//!
//! * the tape builder asks *can I build it from a byte tape **and will its `Display` re-parse**?*
//! * the unit-test emitter asks *can I build it from STATIC leaf values, with no recursion?*
//! * the term generators ask *can I build it AT DEPTH, with a random or enumerated filling?*
//!
//! A single boolean cannot be right for all three, and forcing one would either drop rules the
//! tape builder can handle or emit unparseable text. So the invariant is **not** that the answers
//! agree — it is that **the disagreement is computed from ONE place**. That is what
//! [`generatability`] is: one entry point with the **generator as a PARAMETER, not a second
//! implementation**. The intersections then become a printed, asserted matrix
//! ([`tests::the_intersection_matrix_is_computed_not_written_down`]) instead of an accident nobody
//! measured.
//!
//! The discipline is lifted verbatim in spirit from
//! `gen/runtime/dovetail_report.rs::collection_carrier`:
//!
//! > *THE single classification; every other predicate in this module is a projection of it, so
//! > the AC lane and the ordered lane cannot drift apart.*
//!
//! and its arity lesson applies here too — *"two outcomes cannot express three carriers"* is why
//! [`GeneratorGap`] is an enum and not a `bool`.
//!
//! # The enforcement seam
//!
//! [`tape_rule_gap`], [`tape_variant_gap`], [`unit_variant_gap`] and [`term_rule_gap`] are the
//! **only** implementations of these tests. The generators call them on the hot path; the census
//! calls the same four through [`generatability`]. There is no second implementation for the two
//! to drift apart from — which is exactly the failure `desugar_for_rows` had: a correct function,
//! tested, called by the COMPARISON path and not by the path that RAN.
//!
//! # ⚠ `InternalSurface` IS PORTED, NOT DELETED — the plan said otherwise and was wrong
//!
//! #150's plan carried a "cheapest falsifier": *"Deleting `rule_has_internal_surface` must move
//! ZERO generated bytes… ★ `:331` is DELETED, not ported. The tape builder ALREADY excluded both
//! `__` rules."* Measured 2026-07-30 by disabling the gate and rebuilding `-p languages`:
//!
//! ```text
//!   FILES WHOSE BYTES MOVED: 2
//!     target/generated/rholang/strategies.rs
//!     target/generated/rholang/tests_prop.rs
//!   the Proc tape modulus:  % 124  ─▶  % 126
//!   newly emitted:          Proc::GuardThen(f0, f1)
//!                           Proc::CommWhere(f0, f1, f2, f3, f4)
//! ```
//!
//! The gate is the ONLY thing excluding `__guard_then` and `__comm_where`, whose `Display` the
//! parser cannot re-lex (`strategies.rs`'s own comment records that the third such rule, `__ppar`,
//! *"did not parse at all"*). So it is a real classified gap: [`GeneratorGap::InternalSurface`].
//! Source and generated output were restored byte-identically and verified by md5 — a falsifier
//! you run and then leave the tree changed has become an edit.

