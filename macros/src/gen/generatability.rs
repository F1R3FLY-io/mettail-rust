/// Can `generator` build a term for `rule`?
///
/// This is what the census calls. The generators call the same four sub-classifiers below on
/// their hot paths, so "what the generator skips" and "what the census measures" are the same
/// computation rather than two that happen to agree.
pub(crate) fn generatability(
    rule: &GrammarRule,
    category: &str,
    language: &LanguageDef,
    generator: Generator,
) -> Generatability {
    let refuse = |gap: Option<GeneratorGap>| match gap {
        Some(gap) => Generatability::Refused(gap),
        None => Generatability::Buildable,
    };
    match generator {
        Generator::TapeBuilder => {
            // Two layers, in the order the generator applies them: the RULE-level `__` gate in
            // `collect_spec_only_variants`, then the VARIANT-level gates in `classify_variants`.
            if let Some(gap) = tape_rule_gap(rule) {
                return Generatability::Refused(gap);
            }
            let variant = crate::gen::term_ops::subst::rule_to_variant_kind(rule, language);
            refuse(tape_variant_gap(&variant, category, language))
        },
        Generator::UnitTest => {
            let variant = crate::gen::term_ops::subst::rule_to_variant_kind(rule, language);
            refuse(unit_variant_gap(&variant, language))
        },
        Generator::RandomTerm | Generator::ExhaustiveTerm => refuse(term_rule_gap(rule)),
    }
}

