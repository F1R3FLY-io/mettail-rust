//! **G1 — spec locality.** No file the `language!` macro authors may live outside
//! `target/`.
//!
//! # The property, and why it is the one worth asserting
//!
//! Three writers in this crate emit files during macro expansion. Historically each
//! computed its destination from `CARGO_MANIFEST_DIR` and then walked to a *hardcoded*
//! package: `languages/tests/`, `languages/src/bin/`, `languages/src/generated/`. The
//! destination therefore did not depend on which crate was compiling, and the
//! consequence was structural rather than cosmetic — **the workspace could not be built
//! without mutating tracked files**. Adding or removing a spec in `languages/src/`
//! rewrote the worktree.
//!
//! The fix is that every writer routes through [`crate::logic::writer`], whose
//! `lang_generated_dir` resolves `<workspace-root>/target/generated/<lang>/`. This test
//! is the standing proof that the fix holds: it asserts that the **set** of
//! macro-authored files outside `target/` is EMPTY, and on failure it *enumerates the
//! offenders*. A set-emptiness assertion cannot decay into a threshold that someone
//! later bumps; there is no number to adjust.
//!
//! # How authorship is identified
//!
//! Each writer stamps a header into the first lines of what it emits. The scan looks for
//! those exact stamps, in the first [`HEADER_WINDOW_LINES`] lines only. The window is
//! what separates AUTHORSHIP from QUOTATION: a generated file *opens* with its stamp,
//! whereas the writer's own source code contains the same literal as a format string
//! several hundred lines in, and documentation quotes it in prose. Without the window,
//! this test would flag its own generators.
//!
//! # Anti-vacuity
//!
//! A scan that matches nothing looks exactly like a scan that has nothing to match, so
//! three independent conditions keep this test honest:
//!
//! 1. [`stamps_are_still_what_the_writers_emit`] reads the writer sources and requires
//!    each stamp literal to still appear there. If a writer's header text is reworded,
//!    this test fails LOUDLY instead of quietly matching nothing forever after.
//! 2. [`the_stamp_predicate_distinguishes_authorship_from_quotation`] exercises the
//!    predicate on synthetic inputs, so the matcher is known to work on a file that
//!    really does carry a stamp.
//! 3. [`macro_authored_files_live_only_under_target`] requires the sweep to have read a
//!    substantial number of candidate files before it is allowed to report success.

use std::collections::BTreeSet;
use std::fs;
use std::path::{Path, PathBuf};

/// How many leading lines of a file may carry an authorship stamp.
///
/// The test-suite and simulation stamps are line 1; the Blockly stamp is line 2 (a
/// human-readable title precedes it). Five lines is comfortably past both and still far
/// short of the mid-file positions where the generators hold these literals as format
/// strings.
const HEADER_WINDOW_LINES: usize = 5;

/// One writer's authorship stamp, paired with the source file that emits it.
///
/// The pairing is what makes [`stamps_are_still_what_the_writers_emit`] possible: the
/// test can go and check that the generator still says what this table claims it says.
struct Stamp {
    /// Literal text stamped into the head of every file this writer emits.
    marker: &'static str,
    /// Repo-relative path of the generator that emits `marker`.
    emitted_by: &'static str,
}

/// Every authorship stamp the `language!` expansion can put on disk.
const STAMPS: &[Stamp] = &[
    Stamp {
        marker: "AUTO-GENERATED by language! macro",
        emitted_by: "macros/src/gen/test_gen/mod.rs",
    },
    Stamp {
        marker: "AUTO-GENERATED simulation binary for",
        emitted_by: "macros/src/gen/test_gen/simulation_binary.rs",
    },
    Stamp {
        marker: "DO NOT EDIT - generated by MeTTaIL theory! macro",
        emitted_by: "macros/src/gen/blockly/writer.rs",
    },
];

fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("the macros crate has a workspace parent")
        .to_path_buf()
}

fn repo_relative(path: &Path) -> String {
    path.strip_prefix(repo_root())
        .unwrap_or(path)
        .to_string_lossy()
        .replace('\\', "/")
}

/// Which stamp, if any, this content carries as an AUTHORSHIP claim.
///
/// Only the first [`HEADER_WINDOW_LINES`] lines are considered — see the module
/// documentation for why the window is the whole point.
fn authorship_stamp(content: &str) -> Option<&'static str> {
    let head = content
        .lines()
        .take(HEADER_WINDOW_LINES)
        .collect::<Vec<_>>()
        .join("\n");
    STAMPS
        .iter()
        .find(|stamp| head.contains(stamp.marker))
        .map(|stamp| stamp.marker)
}

/// Whether the repository-wide sweep declines to enter a directory.
///
/// `target` is precisely the destination the macro is now required to use, so it is not
/// a candidate — scanning it would report every legitimately-generated file as an
/// offender. `.git` is object storage, dot-directories are tooling state, and
/// `scratchpad` is the documented wipeable campaign area (gitignored, never a build
/// input), so a stale probe left in one must not be able to fail this suite.
fn is_swept_over(directory_name: &str) -> bool {
    directory_name.starts_with('.') || matches!(directory_name, "target" | "scratchpad")
}

/// The extensions the three writers can emit: Rust sources and Blockly TypeScript.
///
/// Restricting by extension keeps prose out of the candidate set. Design notes and
/// captured session transcripts quote these stamps freely, and a quotation is not an
/// artifact.
fn is_candidate_extension(path: &Path) -> bool {
    matches!(path.extension().and_then(|ext| ext.to_str()), Some("rs") | Some("ts"))
}

/// Every macro-authored file outside `target/`, with the stamp that identified it, and
/// the number of candidate files read to find them.
fn macro_authored_files_outside_target() -> (BTreeSet<(String, &'static str)>, usize) {
    let mut pending = vec![repo_root()];
    let mut offenders = BTreeSet::new();
    let mut candidates_read = 0usize;

    while let Some(path) = pending.pop() {
        let Ok(metadata) = fs::symlink_metadata(&path) else {
            continue; // a broken symlink is not an artifact
        };
        if metadata.is_symlink() {
            continue; // follow nothing: the target is visited on its own merits
        }
        if metadata.is_dir() {
            let name = path
                .file_name()
                .and_then(|name| name.to_str())
                .unwrap_or("");
            if is_swept_over(name) {
                continue;
            }
            let Ok(entries) = fs::read_dir(&path) else {
                continue;
            };
            for entry in entries {
                pending.push(entry.expect("repository directory entry").path());
            }
        } else if is_candidate_extension(&path) {
            candidates_read += 1;
            let content = fs::read_to_string(&path).unwrap_or_default();
            if let Some(marker) = authorship_stamp(&content) {
                offenders.insert((repo_relative(&path), marker));
            }
        }
    }

    (offenders, candidates_read)
}

/// **G1.** The set of macro-authored files outside `target/` is empty.
#[test]
fn macro_authored_files_live_only_under_target() {
    let (offenders, candidates_read) = macro_authored_files_outside_target();

    // Anti-vacuity: a sweep that read nothing would report an empty offender set for
    // the wrong reason. The workspace holds thousands of `.rs` files.
    assert!(
        candidates_read >= 500,
        "the repository sweep read only {candidates_read} candidate file(s); it is not \
         reaching the source tree, so an empty offender set would mean nothing"
    );

    let report = offenders
        .iter()
        .map(|(path, marker)| format!("  {path}  [{marker}]"))
        .collect::<Vec<_>>()
        .join("\n");
    assert!(
        offenders.is_empty(),
        "{} file(s) outside `target/` carry a `language!` authorship stamp, so the \
         workspace cannot be built without mutating them:\n{}\n\nEvery writer must \
         route through `macros/src/logic/writer.rs` (`write_lang_module` /\n\
         `spill_and_include`), which resolves `<workspace-root>/target/generated/<lang>/`. \
         A generated file that must be visible to cargo gets a HAND-WRITTEN host that \
         includes it from there; the host is authored by whoever adds the language and \
         carries no stamp.",
        offenders.len(),
        report,
    );
}

/// **Anti-vacuity 1.** Every stamp this test looks for is still emitted by the writer
/// this test attributes it to.
#[test]
fn stamps_are_still_what_the_writers_emit() {
    for stamp in STAMPS {
        let source_path = repo_root().join(stamp.emitted_by);
        let source = fs::read_to_string(&source_path)
            .unwrap_or_else(|err| panic!("failed to read {}: {err}", source_path.display()));
        assert!(
            source.contains(stamp.marker),
            "{} no longer contains the authorship stamp {:?} that \
             `macro_authored_files_live_only_under_target` searches for. Either the \
             writer was reworded — in which case update `STAMPS` — or the writer was \
             removed, in which case drop its entry. Leaving the table stale would make \
             the locality guard silently stop covering this writer.",
            stamp.emitted_by,
            stamp.marker,
        );
    }
}

/// **Anti-vacuity 2.** The matcher really does fire on a stamped file, and really does
/// not fire on a file that merely mentions a stamp.
#[test]
fn the_stamp_predicate_distinguishes_authorship_from_quotation() {
    let authored = "// AUTO-GENERATED by language! macro for Calculator (unit) — do not edit\n\
                    // Regenerated on each compilation of the language definition.\n\n\
                    fn nothing() {}\n";
    assert_eq!(
        authorship_stamp(authored),
        Some("AUTO-GENERATED by language! macro"),
        "the matcher must recognise a file that opens with a writer's stamp"
    );

    let blockly = "// Generated Blockly blocks for Calculator language\n\
                   // DO NOT EDIT - generated by MeTTaIL theory! macro\n\
                   // Changes will be overwritten on next build\n";
    assert_eq!(
        authorship_stamp(blockly),
        Some("DO NOT EDIT - generated by MeTTaIL theory! macro"),
        "the Blockly stamp sits on line 2, inside the header window"
    );

    let quotation = (0..HEADER_WINDOW_LINES + 1)
        .map(|_| "// prose\n")
        .collect::<String>()
        + "// AUTO-GENERATED by language! macro for Calculator (unit) — do not edit\n";
    assert_eq!(
        authorship_stamp(&quotation),
        None,
        "a stamp quoted past the header window is a mention, not an authorship claim; \
         this is what keeps the generators themselves out of the offender set"
    );
}
