#[derive(Clone, Debug)]
struct ChannelAuthorityState {
    epoch: u64,
    rights: SpaceRights,
}

/// Capability-separated transaction kernel for one theorem-indexed channel.
/// Successful commit callbacks run while both the installed-language epoch and
/// the channel-authority epoch are read-locked.  A failed check never invokes
/// the callback, which is the adapter's atomic-mutation boundary.
pub struct TheoremChannelKernel {
    descriptor: TheoremChannelDescriptor,
    checker: StructuralTheoremChecker,
    authority: RwLock<ChannelAuthorityState>,
    proof_cache: RwLock<ProofCache>,
}

impl TheoremChannelKernel {
    pub fn new(
        descriptor: TheoremChannelDescriptor,
        rights: SpaceRights,
        checker: StructuralTheoremChecker,
        proof_cache_capacity: usize,
    ) -> Self {
        Self {
            descriptor,
            checker,
            authority: RwLock::new(ChannelAuthorityState { epoch: 0, rights }),
            proof_cache: RwLock::new(ProofCache::new(proof_cache_capacity)),
        }
    }

    pub fn descriptor(&self) -> &TheoremChannelDescriptor {
        &self.descriptor
    }

    pub fn prepare_produce(
        &self,
        table: &InstalledLanguageTable,
        handle: &InstalledLanguageHandle,
        term_hash: TermHash,
    ) -> Result<PreparedProduce, TheoremChannelError> {
        table
            .authorize(handle, LanguageRight::Publish)
            .map_err(TheoremChannelError::LanguageAccess)?;
        if handle.fingerprint() != self.descriptor.language {
            return Err(TheoremChannelError::LanguageMismatch);
        }
        let term = CanonicalFltTerm::structurally_admitted(
            self.descriptor.language,
            self.descriptor.category,
            term_hash,
        );
        let authority = self
            .authority
            .read()
            .map_err(|_| TheoremChannelError::Poisoned)?;
        if !authority.rights.contains(SpaceRight::Produce) {
            return Err(TheoremChannelError::MissingSpaceRight(SpaceRight::Produce));
        }
        let certificate = self
            .checker
            .check(term, self.descriptor.channel_theorem)
            .map_err(TheoremChannelError::Certificate)?;
        self.cache_verified(&certificate)?;
        Ok(PreparedProduce {
            channel_id: self.descriptor.id,
            epoch: authority.epoch,
            handle: handle.clone(),
            message: AdmittedMessage { term, certificate },
        })
    }

    pub fn commit_produce<R>(
        &self,
        table: &InstalledLanguageTable,
        prepared: PreparedProduce,
        commit: impl FnOnce(AdmittedMessage) -> R,
    ) -> Result<R, TheoremChannelError> {
        if prepared.channel_id != self.descriptor.id {
            return Err(TheoremChannelError::WrongChannel);
        }
        table
            .with_authorized(&prepared.handle, LanguageRight::Publish, |_| {
                let authority = self
                    .authority
                    .read()
                    .map_err(|_| TheoremChannelError::Poisoned)?;
                if authority.epoch != prepared.epoch {
                    return Err(TheoremChannelError::StaleEpoch);
                }
                if !authority.rights.contains(SpaceRight::Produce) {
                    return Err(TheoremChannelError::MissingSpaceRight(SpaceRight::Produce));
                }
                self.verify_cached(prepared.message.certificate())?;
                Ok(commit(prepared.message))
            })
            .map_err(TheoremChannelError::LanguageAccess)?
    }

    pub fn prepare_consume(
        &self,
        table: &InstalledLanguageTable,
        handle: &InstalledLanguageHandle,
        message: &AdmittedMessage,
        pattern: &TypedPatternDescriptor,
        capture_hashes: &[TermHash],
    ) -> Result<PreparedConsume, TheoremChannelError> {
        table
            .authorize(handle, LanguageRight::Match)
            .map_err(TheoremChannelError::LanguageAccess)?;
        if handle.fingerprint() != self.descriptor.language {
            return Err(TheoremChannelError::LanguageMismatch);
        }
        let channel_message = self.reclassify_channel_message(message)?;
        if message.term.language != pattern.language
            || message.term.category != pattern.category
            || pattern.language != self.descriptor.language
            || pattern.category != self.descriptor.category
            || pattern
                .exact_hash
                .is_some_and(|hash| hash != message.term.term_hash)
        {
            return Err(TheoremChannelError::PatternMismatch);
        }
        if capture_hashes.len() != pattern.capture_categories.len() {
            return Err(TheoremChannelError::CaptureTelescopeMismatch);
        }
        let mut capture_certificates = Vec::with_capacity(capture_hashes.len());
        for (term_hash, category) in capture_hashes.iter().zip(&pattern.capture_categories) {
            let capture = CanonicalFltTerm::structurally_admitted(
                self.descriptor.language,
                *category,
                *term_hash,
            );
            let certificate = self
                .checker
                .check(capture, AdmissionTheorem::Membership(*category))
                .map_err(TheoremChannelError::Certificate)?;
            self.cache_verified(&certificate)?;
            capture_certificates.push(certificate);
        }
        let authority = self
            .authority
            .read()
            .map_err(|_| TheoremChannelError::Poisoned)?;
        if !authority.rights.contains(SpaceRight::Consume) {
            return Err(TheoremChannelError::MissingSpaceRight(SpaceRight::Consume));
        }
        Ok(PreparedConsume {
            channel_id: self.descriptor.id,
            epoch: authority.epoch,
            handle: handle.clone(),
            evidence: CheckedMatchEvidence {
                pattern_id: pattern.id,
                message: channel_message,
                captures: capture_certificates,
            },
        })
    }

    pub fn commit_consume<R>(
        &self,
        table: &InstalledLanguageTable,
        prepared: PreparedConsume,
        commit: impl FnOnce(CheckedMatchEvidence) -> R,
    ) -> Result<R, TheoremChannelError> {
        if prepared.channel_id != self.descriptor.id {
            return Err(TheoremChannelError::WrongChannel);
        }
        table
            .with_authorized(&prepared.handle, LanguageRight::Match, |_| {
                let authority = self
                    .authority
                    .read()
                    .map_err(|_| TheoremChannelError::Poisoned)?;
                if authority.epoch != prepared.epoch {
                    return Err(TheoremChannelError::StaleEpoch);
                }
                if !authority.rights.contains(SpaceRight::Consume) {
                    return Err(TheoremChannelError::MissingSpaceRight(SpaceRight::Consume));
                }
                self.verify_cached(prepared.evidence.message.certificate())?;
                for certificate in &prepared.evidence.captures {
                    self.verify_cached(certificate)?;
                }
                Ok(commit(prepared.evidence))
            })
            .map_err(TheoremChannelError::LanguageAccess)?
    }

    /// Rights can only decrease.  Epoch advancement invalidates every prepared
    /// transaction, including one whose proof certificate is cached.
    pub fn attenuate_space_rights(
        &self,
        requested: &SpaceRights,
    ) -> Result<u64, TheoremChannelError> {
        let mut authority = self
            .authority
            .write()
            .map_err(|_| TheoremChannelError::Poisoned)?;
        authority.rights = authority.rights.attenuate(requested);
        authority.epoch = authority
            .epoch
            .checked_add(1)
            .ok_or(TheoremChannelError::EpochExhausted)?;
        Ok(authority.epoch)
    }

    pub fn revoke(&self) -> Result<u64, TheoremChannelError> {
        self.attenuate_space_rights(&SpaceRights::none())
    }

    fn check_term_identity(&self, term: CanonicalFltTerm) -> Result<(), TheoremChannelError> {
        if term.language != self.descriptor.language {
            return Err(TheoremChannelError::LanguageMismatch);
        }
        if term.category != self.descriptor.category {
            return Err(TheoremChannelError::CategoryMismatch);
        }
        Ok(())
    }

    /// Transport an already admitted term into this channel's theorem fibre.
    /// The original certificate establishes the canonical term identity; the
    /// local total checker then proves the channel predicate instead of
    /// trusting certificate provenance or requiring nominal theorem equality.
    fn reclassify_channel_message(
        &self,
        message: &AdmittedMessage,
    ) -> Result<AdmittedMessage, TheoremChannelError> {
        self.check_term_identity(message.term)?;
        self.verify_cached(message.certificate())?;
        let certificate = self
            .checker
            .check(message.term, self.descriptor.channel_theorem)
            .map_err(TheoremChannelError::Certificate)?;
        self.cache_verified(&certificate)?;
        Ok(AdmittedMessage { term: message.term, certificate })
    }

    fn cache_verified(
        &self,
        certificate: &AdmissionCertificate,
    ) -> Result<(), TheoremChannelError> {
        self.checker
            .verify(certificate)
            .map_err(TheoremChannelError::Certificate)?;
        self.proof_cache
            .write()
            .map_err(|_| TheoremChannelError::Poisoned)?
            .insert(ProofCacheKey::from(certificate));
        Ok(())
    }

    fn verify_cached(&self, certificate: &AdmissionCertificate) -> Result<(), TheoremChannelError> {
        let key = ProofCacheKey::from(certificate);
        if self
            .proof_cache
            .read()
            .map_err(|_| TheoremChannelError::Poisoned)?
            .contains(&key)
        {
            return Ok(());
        }
        self.cache_verified(certificate)
    }
}

#[derive(Debug)]
pub enum TheoremChannelError {
    InvalidRefinement,
    LanguageMismatch,
    CategoryMismatch,
    WrongChannel,
    PatternMismatch,
    CaptureTelescopeMismatch,
    CaptureLimitExceeded,
    MissingSpaceRight(SpaceRight),
    StaleEpoch,
    EpochExhausted,
    Poisoned,
    Certificate(CertificateError),
    LanguageAccess(LanguageAccessError),
}

impl fmt::Display for TheoremChannelError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::InvalidRefinement => {
                formatter.write_str("the channel theorem does not refine the space theorem")
            },
            Self::LanguageMismatch => formatter.write_str("FLT language does not match channel"),
            Self::CategoryMismatch => formatter.write_str("FLT category does not match channel"),
            Self::WrongChannel => {
                formatter.write_str("prepared transaction belongs to another channel")
            },
            Self::PatternMismatch => {
                formatter.write_str("typed FLT pattern does not match message")
            },
            Self::CaptureTelescopeMismatch => {
                formatter.write_str("capture evidence does not match the typed telescope")
            },
            Self::CaptureLimitExceeded => {
                formatter.write_str("capture telescope exceeds its limit")
            },
            Self::MissingSpaceRight(right) => write!(formatter, "missing space right {right:?}"),
            Self::StaleEpoch => {
                formatter.write_str("prepared transaction has a stale authority epoch")
            },
            Self::EpochExhausted => formatter.write_str("channel authority epoch exhausted"),
            Self::Poisoned => formatter.write_str("theorem-channel state lock is poisoned"),
            Self::Certificate(error) => write!(formatter, "certificate error: {error}"),
            Self::LanguageAccess(error) => write!(formatter, "language access error: {error:?}"),
        }
    }
}

impl std::error::Error for TheoremChannelError {}

#[cfg(test)]
mod tests {
    use super::*;

    fn hash(byte: u8) -> TermHash {
        TermHash([byte; 32])
    }

    #[test]
    fn normalized_meet_is_commutative_idempotent_and_refines_membership() {
        let category = CategoryId(7);
        let membership = AdmissionTheorem::membership(category);
        let exact = AdmissionTheorem::exact(category, hash(3));
        assert_eq!(membership.meet(exact), exact);
        assert_eq!(exact.meet(membership), exact);
        assert_eq!(exact.meet(exact), exact);
        assert!(exact.refines(membership));
        assert!(!membership.refines(exact));
        assert_eq!(
            membership.meet(AdmissionTheorem::membership(CategoryId(8))),
            AdmissionTheorem::Bottom
        );
    }

    #[test]
    fn certificate_and_cache_bind_every_consensus_identity_field() {
        let checker = StructuralTheoremChecker::default();
        let term = CanonicalFltTerm::structurally_admitted([1; 32], CategoryId(2), hash(4));
        let certificate = checker
            .check(term, AdmissionTheorem::membership(CategoryId(2)))
            .expect("membership certificate");
        checker.verify(&certificate).expect("certificate verifies");
        let key = ProofCacheKey::from(&certificate);
        assert_eq!(key.language, [1; 32]);
        assert_eq!(key.term_hash, hash(4));
        assert_eq!(key.checker_abi, STRUCTURAL_THEOREM_CHECKER_ABI_V1);
        assert_eq!(key.limit_profile, STRUCTURAL_THEOREM_LIMIT_PROFILE_V1);

        let mut cache = ProofCache::new(1);
        assert!(cache.insert(key.clone()));
        assert!(cache.contains(&key));
        let other = checker
            .check(
                CanonicalFltTerm::structurally_admitted([1; 32], CategoryId(2), hash(5)),
                AdmissionTheorem::membership(CategoryId(2)),
            )
            .expect("second certificate");
        assert!(!cache.insert(ProofCacheKey::from(&other)));
        assert_eq!(cache.len(), 1);
    }

    #[test]
    fn channel_refinement_rejects_cross_category_and_weaker_claims() {
        let member = AdmissionTheorem::membership(CategoryId(1));
        let exact = AdmissionTheorem::exact(CategoryId(1), hash(9));
        assert!(TheoremChannelDescriptor::new([3; 32], CategoryId(1), exact, member).is_ok());
        assert!(matches!(
            TheoremChannelDescriptor::new([3; 32], CategoryId(1), member, exact),
            Err(TheoremChannelError::InvalidRefinement)
        ));
        assert!(matches!(
            TheoremChannelDescriptor::new(
                [3; 32],
                CategoryId(1),
                AdmissionTheorem::membership(CategoryId(2)),
                member,
            ),
            Err(TheoremChannelError::CategoryMismatch)
        ));
    }
}
