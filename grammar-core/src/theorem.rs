//! Source-neutral theorem certificates and typed-channel transaction protocol.
//!
//! Grammar recognition proves that a reflected value belongs to a syntactic
//! category.  Stateful admission is a separate judgment: a channel is indexed
//! by an installed language and a theorem, and mutation is permitted only after
//! a certificate has been checked and both language and space authority have
//! been revalidated at the commit boundary.  This module owns that small,
//! runtime-neutral kernel; it deliberately owns no tuple-space persistence.

use crate::{
    CategoryId, InstalledLanguageHandle, InstalledLanguageTable, LanguageAccessError, LanguageRight,
};
use serde::{Deserialize, Serialize};
use std::collections::BTreeSet;
use std::fmt;
use std::sync::RwLock;

pub const STRUCTURAL_THEOREM_CHECKER_ABI_V1: &str = "mettail-structural-theorem-checker/1";
pub const STRUCTURAL_THEOREM_LIMIT_PROFILE_V1: &str = "mettail-structural-theorem-limits/1";

#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
pub struct TheoremId(pub [u8; 32]);

#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
pub struct TermHash(pub [u8; 32]);

/// Canonical quotient of conjunctions generated by category membership and
/// exact-term predicates.
///
/// `meet` is associative, commutative, and idempotent.  Contradictory
/// conjunctions normalize to `Bottom`, so neither equality nor refinement ever
/// traverses a user-sized theorem tree.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
pub enum AdmissionTheorem {
    Bottom,
    Membership(CategoryId),
    ExactTerm {
        category: CategoryId,
        term_hash: TermHash,
    },
}

impl AdmissionTheorem {
    pub const fn membership(category: CategoryId) -> Self {
        Self::Membership(category)
    }

    pub const fn exact(category: CategoryId, term_hash: TermHash) -> Self {
        Self::ExactTerm { category, term_hash }
    }

    pub fn id(self) -> TheoremId {
        let mut hasher = blake3::Hasher::new();
        hasher.update(b"mettail-admission-theorem/1\0");
        match self {
            Self::Bottom => {
                hasher.update(&[0]);
            },
            Self::Membership(category) => {
                hasher.update(&[1]);
                hasher.update(&category.0.to_be_bytes());
            },
            Self::ExactTerm { category, term_hash } => {
                hasher.update(&[2]);
                hasher.update(&category.0.to_be_bytes());
                hasher.update(&term_hash.0);
            },
        }
        TheoremId(*hasher.finalize().as_bytes())
    }

    pub const fn category(self) -> Option<CategoryId> {
        match self {
            Self::Bottom => None,
            Self::Membership(category) | Self::ExactTerm { category, .. } => Some(category),
        }
    }

    pub fn meet(self, other: Self) -> Self {
        match (self, other) {
            (Self::Bottom, _) | (_, Self::Bottom) => Self::Bottom,
            (Self::Membership(left), Self::Membership(right)) => {
                if left.0 == right.0 {
                    Self::Membership(left)
                } else {
                    Self::Bottom
                }
            },
            (
                Self::ExactTerm { category: exact_category, term_hash },
                Self::Membership(member_category),
            )
            | (
                Self::Membership(member_category),
                Self::ExactTerm { category: exact_category, term_hash },
            ) => {
                if exact_category.0 == member_category.0 {
                    Self::ExactTerm { category: exact_category, term_hash }
                } else {
                    Self::Bottom
                }
            },
            (
                Self::ExactTerm {
                    category: left_category,
                    term_hash: left_hash,
                },
                Self::ExactTerm {
                    category: right_category,
                    term_hash: right_hash,
                },
            ) => {
                if left_category.0 == right_category.0 && left_hash.0 == right_hash.0 {
                    Self::ExactTerm {
                        category: left_category,
                        term_hash: left_hash,
                    }
                } else {
                    Self::Bottom
                }
            },
        }
    }

    /// `self` refines `target` when every term satisfying `self` also satisfies
    /// `target`.  Bottom is the initial object of this implication preorder.
    pub fn refines(self, target: Self) -> bool {
        match (self, target) {
            (Self::Bottom, _) => true,
            (_, Self::Bottom) => false,
            (Self::Membership(left), Self::Membership(right)) => left.0 == right.0,
            (
                Self::ExactTerm {
                    category: left_category,
                    term_hash: left_hash,
                },
                Self::ExactTerm {
                    category: right_category,
                    term_hash: right_hash,
                },
            ) => left_category.0 == right_category.0 && left_hash.0 == right_hash.0,
            (
                Self::ExactTerm { category: exact_category, .. },
                Self::Membership(member_category),
            ) => exact_category.0 == member_category.0,
            (Self::Membership(_), Self::ExactTerm { .. }) => false,
        }
    }

    pub fn holds(self, term: CanonicalFltTerm) -> bool {
        match self {
            Self::Bottom => false,
            Self::Membership(category) => category.0 == term.category.0,
            Self::ExactTerm { category, term_hash } => {
                category.0 == term.category.0 && term_hash.0 == term.term_hash.0
            },
        }
    }
}

/// The source-neutral identity of an FLT after an authorized adapter has
/// checked its concrete representation against the installed grammar.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct CanonicalFltTerm {
    language: [u8; 32],
    category: CategoryId,
    term_hash: TermHash,
}

impl CanonicalFltTerm {
    const fn structurally_admitted(
        language: [u8; 32],
        category: CategoryId,
        term_hash: TermHash,
    ) -> Self {
        Self { language, category, term_hash }
    }

    pub const fn language(self) -> [u8; 32] {
        self.language
    }

    pub const fn category(self) -> CategoryId {
        self.category
    }

    pub const fn term_hash(self) -> TermHash {
        self.term_hash
    }
}

