//! Runtime diagnostics infrastructure.
//!
//! Stage 7 of W7 plan v5.1. Provides a thread-local queue for diagnostic
//! warnings emitted from generated code paths (Display canonicalization,
//! parser ambiguity exposure, etc.).
//!
//! ## D11 — Display canonicalization warning
//!
//! Emitted when a `*Inner::Ambiguous(alts)` variant is rendered via
//! `std::fmt::Display`. The Display impl always writes `alts[0]` (the
//! lex-min primary), but emits a D11 warning so consumers (REPL, LSP
//! diagnostics, parity tests) can detect that disambiguation took place.
//!
//! Per plan v5.1 mandate M10: "Display Option D — canonicalize to lex-best
//! primary; emit `[LANG-D11]` warning."
//!
//! ## Usage
//!
//! The hidden lines below stand in for the generated `*Inner::Ambiguous`
//! variant and its `Display` impl, so the illustrative call is compiled
//! against the real [`emit_d11`] signature rather than merely asserted.
//!
//! ```
//! # struct ProcInnerAmbiguous(Vec<String>);
//! # impl std::fmt::Display for ProcInnerAmbiguous {
//! #     fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
//! #         let alts = &self.0;
//! // Generated by macros (Display impl for *Inner::Ambiguous):
//! mettail_runtime::diagnostics::emit_d11(
//!     "Calculator",
//!     "Proc",
//!     alts.len(),
//! );
//! write!(f, "{}", alts[0])
//! #     }
//! # }
//! # let rendered = ProcInnerAmbiguous(vec!["1 + 2".into(), "1 + 2".into()]).to_string();
//! # assert_eq!(rendered, "1 + 2");
//! # assert_eq!(mettail_runtime::diagnostics::take_diagnostics().len(), 1);
//! ```
//!
//! Consumers retrieve the diagnostic queue:
//!
//! ```
//! let warnings = mettail_runtime::diagnostics::take_diagnostics();
//! for w in warnings {
//!     eprintln!("{}", w);
//! }
//! ```

use std::cell::RefCell;

thread_local! {
    /// Per-thread queue of pending diagnostic messages.
    static DIAGNOSTICS: RefCell<Vec<Diagnostic>> = const { RefCell::new(Vec::new()) };
}

/// A diagnostic message tagged with its issuing code.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Diagnostic {
    /// Diagnostic code (e.g., "D11"). Stable across releases.
    pub code: String,
    /// Language name (e.g., "Calculator"). May be empty for cross-language diagnostics.
    pub language: String,
    /// Category name (e.g., "Proc"). May be empty for non-category-scoped diagnostics.
    pub category: String,
    /// Human-readable message.
    pub message: String,
}

impl Diagnostic {
    /// Format the diagnostic as `[LANG-CODE] message`.
    pub fn render(&self) -> String {
        let prefix = if self.language.is_empty() {
            format!("[{}]", self.code)
        } else {
            format!("[{}-{}]", self.language, self.code)
        };
        if self.category.is_empty() {
            format!("{} {}", prefix, self.message)
        } else {
            format!("{} category={}: {}", prefix, self.category, self.message)
        }
    }
}

impl std::fmt::Display for Diagnostic {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", self.render())
    }
}

/// Push a diagnostic onto the thread-local queue.
pub fn emit(diagnostic: Diagnostic) {
    DIAGNOSTICS.with(|q| q.borrow_mut().push(diagnostic));
}

/// Convenience: emit a D11 (Display canonicalization) warning.
///
/// Called by generated `Display` impls when an `Ambiguous(alts)` variant
/// is rendered. Records the language, category, and how many alternatives
/// existed; lex-best (alts[0]) was selected as the rendered representation.
pub fn emit_d11(language: &str, category: &str, alt_count: usize) {
    emit(Diagnostic {
        code: "D11".to_string(),
        language: language.to_string(),
        category: category.to_string(),
        message: format!(
            "Display canonicalization: {} alternatives present, lex-best primary chosen",
            alt_count,
        ),
    });
}

/// Phase D.8 (2026-05-17, M14.5): enriched D11 emission with the
/// complete alt-display list.
///
/// `alt_displays`: typically the result of `inner.all_displays()` —
/// one `String` per parse alternative. The diagnostic message includes
/// the full list so consumers (REPL/LSP/parity tests) see every
/// alternative the parser preserved, not just the lex-best primary.
///
/// Use this variant when you have the displays handy (e.g., from the
/// Display impl on Ambiguous, or from a diagnostic-enrichment pass
/// over a failed evaluation). The plain [`emit_d11`] remains for
/// call sites that only have the alt count.
pub fn emit_d11_with_alts(language: &str, category: &str, alt_displays: &[String]) {
    let alt_count = alt_displays.len();
    let alt_list = if alt_displays.is_empty() {
        String::from("[]")
    } else {
        format!("[{}]", alt_displays.join(" | "))
    };
    emit(Diagnostic {
        code: "D11".to_string(),
        language: language.to_string(),
        category: category.to_string(),
        message: format!(
            "Display canonicalization: {} alternatives present, lex-best primary chosen; alts={}",
            alt_count, alt_list,
        ),
    });
}

/// Drain the thread-local diagnostic queue, returning all pending messages.
///
/// Consumers (REPL, LSP, tests) call this periodically to surface warnings.
pub fn take_diagnostics() -> Vec<Diagnostic> {
    DIAGNOSTICS.with(|q| std::mem::take(&mut *q.borrow_mut()))
}

/// Number of pending diagnostics in the thread-local queue (without draining).
pub fn pending_count() -> usize {
    DIAGNOSTICS.with(|q| q.borrow().len())
}

/// Clear the thread-local diagnostic queue without returning anything.
pub fn clear_diagnostics() {
    DIAGNOSTICS.with(|q| q.borrow_mut().clear());
}

