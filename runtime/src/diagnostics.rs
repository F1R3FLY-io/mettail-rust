#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn diagnostic_renders_with_language_and_category() {
        let d = Diagnostic {
            code: "D11".to_string(),
            language: "Calculator".to_string(),
            category: "Proc".to_string(),
            message: "Display canonicalization: 2 alternatives present".to_string(),
        };
        assert_eq!(
            d.render(),
            "[Calculator-D11] category=Proc: Display canonicalization: 2 alternatives present"
        );
    }

    #[test]
    fn diagnostic_renders_without_category() {
        let d = Diagnostic {
            code: "D11".to_string(),
            language: "Rholang".to_string(),
            category: String::new(),
            message: "test".to_string(),
        };
        assert_eq!(d.render(), "[Rholang-D11] test");
    }

    #[test]
    fn diagnostic_renders_without_language() {
        let d = Diagnostic {
            code: "D11".to_string(),
            language: String::new(),
            category: String::new(),
            message: "anonymous".to_string(),
        };
        assert_eq!(d.render(), "[D11] anonymous");
    }

    #[test]
    fn emit_and_take_round_trip() {
        clear_diagnostics();
        emit_d11("Calculator", "Proc", 3);
        emit_d11("Calculator", "Bool", 2);
        let out = take_diagnostics();
        assert_eq!(out.len(), 2);
        assert_eq!(out[0].code, "D11");
        assert_eq!(out[0].language, "Calculator");
        assert_eq!(out[0].category, "Proc");
        assert!(out[0].message.contains("3 alternatives"));
        // Queue is drained.
        assert_eq!(pending_count(), 0);
    }

    #[test]
    fn pending_count_reflects_queue() {
        clear_diagnostics();
        assert_eq!(pending_count(), 0);
        emit_d11("X", "Y", 2);
        assert_eq!(pending_count(), 1);
        emit_d11("X", "Y", 3);
        assert_eq!(pending_count(), 2);
        let _ = take_diagnostics();
        assert_eq!(pending_count(), 0);
    }

    #[test]
    fn clear_drops_pending() {
        clear_diagnostics();
        emit_d11("X", "Y", 1);
        emit_d11("X", "Y", 2);
        assert_eq!(pending_count(), 2);
        clear_diagnostics();
        assert_eq!(pending_count(), 0);
    }

    #[test]
    fn diagnostic_display_matches_render() {
        let d = Diagnostic {
            code: "D11".to_string(),
            language: "Calc".to_string(),
            category: "Int".to_string(),
            message: "msg".to_string(),
        };
        assert_eq!(format!("{}", d), d.render());
    }

    #[test]
    fn thread_local_isolation() {
        // Diagnostics are per-thread; one thread emitting does not leak to another.
        clear_diagnostics();
        emit_d11("Main", "Cat", 1);
        let other = std::thread::spawn(|| pending_count());
        let other_count = other.join().expect("thread joined");
        assert_eq!(other_count, 0);
        // Our queue still has the message.
        assert_eq!(pending_count(), 1);
        clear_diagnostics();
    }
}
