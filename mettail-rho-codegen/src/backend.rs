//! Rho-default backend planning.
//!
//! `RhoBackendFlipGate.v` proves the Boolean gate. This module is the Rust-side
//! planner that a runtime selector can consume: it lowers a `LanguageDef`,
//! checks exact coverage, artifact validation, and deadlock diagnostics, and
//! either returns a concrete Rho-default backend plan or all blockers.

use std::collections::{BTreeSet, HashMap, HashSet};

use mettail_ast::grammar::{GrammarItem, GrammarRule, SyntaxExpr, TermParam};
use mettail_ast::language::{BehavioralPred, GuardConfig, LanguageDef, Premise, RewriteRule};
use mettail_ast::types::TypeExpr;
use models::rhoapi::Par;

use crate::flip::{decide_rho_flip, RhoFlipDecision, RhoFlipGates};
use crate::lower::{lower_language_def, RhoLowering};
use crate::validate::{RhoValidationError, ValidatedRhoProgram};

/// Runtime disposition kind for a rule not lowered by the scalar Rho AST
/// generator.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum RhoRejectedRuleDispositionKind {
    /// Covered by a verified native system process or host-side handler.
    NativeHandler,
    /// Covered by a verified external contract supplied by the host runtime.
    ExternalContract,
    /// Covered by a non-scalar Rho AST contract generated by another lowering.
    RhoAstContract,
}

/// Class of predicated-type / guard obligation induced by a `LanguageDef`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum RhoGuardObligationKind {
    /// Runtime predicate over matched values, facts, channels, or named
    /// predicate relations.
    BehavioralPredicate,
    /// Structural pattern predicate such as AC matching, binding shape, or
    /// guarded rewrite pattern structure.
    StructuralPattern,
    /// Registered predicate theory that must supply an effective Boolean
    /// algebra or an equivalent verified theory adapter.
    TheoryRegistration,
    /// Rho-native guarded receive/join/channel scheduling obligation.
    RhoNativeJoin,
}

/// One guard/predicated-type obligation that must be covered before the Rho
/// backend may become the default runtime for a language.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct RhoGuardObligation {
    pub id: String,
    pub kind: RhoGuardObligationKind,
}

impl RhoGuardObligation {
    fn new(id: impl Into<String>, kind: RhoGuardObligationKind) -> Self {
        Self { id: id.into(), kind }
    }
}

/// Disposition kind for a guard/predicated-type obligation.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum RhoGuardDispositionKind {
    /// Covered directly by Dovetail's structural rewrite/pattern semantics.
    DovetailCoreStructural,
    /// Covered by an effective Boolean algebra / symbolic automata theory.
    EffectiveBooleanAlgebra,
    /// Covered by a symbolic finite-state transducer whose output semantics are
    /// part of the associated verification commentary.
    SymbolicFiniteTransducer,
    /// Covered by a Rho-native guarded join / RSpace atomic continuation.
    RhoNativeJoin,
    /// Covered by a verified native host handler.
    NativeHandler,
    /// Covered by an externally supplied verified contract.
    ExternalContract,
}

/// Coverage disposition for one guard/predicated-type obligation.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RhoGuardDisposition {
    pub obligation: String,
    pub kind: RhoGuardDispositionKind,
}

impl RhoGuardDisposition {
    pub fn new(obligation: impl Into<String>, kind: RhoGuardDispositionKind) -> Self {
        Self { obligation: obligation.into(), kind }
    }
}

/// Invalid guard-obligation coverage diagnostics.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum RhoGuardDispositionDiagnostic {
    MissingObligationId,
    DuplicateObligationDisposition {
        obligation: String,
    },
    IncompatibleDisposition {
        obligation: String,
        obligation_kind: RhoGuardObligationKind,
        disposition_kind: RhoGuardDispositionKind,
    },
}

/// Coverage evidence for all guard/predicated-type obligations induced by a
/// `LanguageDef`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum RhoGuardCoverageEvidence {
    /// Accept only languages whose `LanguageDef` induces no guard obligations.
    NoGuardObligations,
    /// Accept only when these dispositions exactly cover the induced obligation
    /// set and every disposition is compatible with its obligation kind.
    CoveredGuardObligations(Vec<RhoGuardDisposition>),
}

impl RhoGuardCoverageEvidence {
    fn covered_dispositions(&self) -> &[RhoGuardDisposition] {
        match self {
            Self::NoGuardObligations => &[],
            Self::CoveredGuardObligations(dispositions) => dispositions,
        }
    }

    fn covered_set(&self) -> BTreeSet<&str> {
        match self {
            Self::NoGuardObligations => BTreeSet::new(),
            Self::CoveredGuardObligations(dispositions) => dispositions
                .iter()
                .map(|disposition| disposition.obligation.as_str())
                .collect(),
        }
    }

    fn uncovered_obligations(&self, obligations: &[RhoGuardObligation]) -> Vec<String> {
        let covered = self.covered_set();
        obligations
            .iter()
            .filter(|obligation| !covered.contains(obligation.id.as_str()))
            .map(|obligation| obligation.id.clone())
            .collect()
    }

    fn extraneous_dispositions(&self, obligations: &[RhoGuardObligation]) -> Vec<String> {
        let expected: BTreeSet<&str> = obligations
            .iter()
            .map(|obligation| obligation.id.as_str())
            .collect();
        self.covered_set()
            .into_iter()
            .filter(|obligation| !expected.contains(obligation))
            .map(ToOwned::to_owned)
            .collect()
    }

    fn invalid_dispositions(
        &self,
        obligations: &[RhoGuardObligation],
    ) -> Vec<RhoGuardDispositionDiagnostic> {
        let mut diagnostics = Vec::new();
        let mut seen = BTreeSet::new();
        let mut duplicate_reported = BTreeSet::new();
        let obligation_kinds = obligations
            .iter()
            .map(|obligation| (obligation.id.as_str(), obligation.kind))
            .collect::<HashMap<_, _>>();

        for disposition in self.covered_dispositions() {
            if disposition.obligation.trim().is_empty() {
                diagnostics.push(RhoGuardDispositionDiagnostic::MissingObligationId);
            } else if !seen.insert(disposition.obligation.as_str())
                && duplicate_reported.insert(disposition.obligation.as_str())
            {
                diagnostics.push(RhoGuardDispositionDiagnostic::DuplicateObligationDisposition {
                    obligation: disposition.obligation.clone(),
                });
            }

            if let Some(obligation_kind) = obligation_kinds.get(disposition.obligation.as_str()) {
                if !guard_disposition_covers(*obligation_kind, disposition.kind) {
                    diagnostics.push(RhoGuardDispositionDiagnostic::IncompatibleDisposition {
                        obligation: disposition.obligation.clone(),
                        obligation_kind: *obligation_kind,
                        disposition_kind: disposition.kind,
                    });
                }
            }
        }

        diagnostics
    }

    fn exactly_covers(&self, obligations: &[RhoGuardObligation]) -> bool {
        self.uncovered_obligations(obligations).is_empty()
            && self.extraneous_dispositions(obligations).is_empty()
            && self.invalid_dispositions(obligations).is_empty()
    }

    fn accepted_dispositions(&self) -> Vec<RhoGuardDisposition> {
        match self {
            Self::NoGuardObligations => Vec::new(),
            Self::CoveredGuardObligations(dispositions) => dispositions.clone(),
        }
    }
}

fn guard_disposition_covers(
    obligation_kind: RhoGuardObligationKind,
    disposition_kind: RhoGuardDispositionKind,
) -> bool {
    use RhoGuardDispositionKind::{
        DovetailCoreStructural, EffectiveBooleanAlgebra, ExternalContract, NativeHandler,
        RhoNativeJoin, SymbolicFiniteTransducer,
    };
    use RhoGuardObligationKind::{
        BehavioralPredicate, RhoNativeJoin as RhoNativeJoinObligation, StructuralPattern,
        TheoryRegistration,
    };

    match obligation_kind {
        BehavioralPredicate => matches!(
            disposition_kind,
            EffectiveBooleanAlgebra
                | SymbolicFiniteTransducer
                | RhoNativeJoin
                | NativeHandler
                | ExternalContract
        ),
        StructuralPattern => matches!(
            disposition_kind,
            DovetailCoreStructural
                | SymbolicFiniteTransducer
                | RhoNativeJoin
                | NativeHandler
                | ExternalContract
        ),
        TheoryRegistration => matches!(
            disposition_kind,
            EffectiveBooleanAlgebra | SymbolicFiniteTransducer | NativeHandler | ExternalContract
        ),
        RhoNativeJoinObligation => {
            matches!(disposition_kind, RhoNativeJoin | NativeHandler | ExternalContract)
        },
    }
}

fn pred_has_structural_component(pred: &BehavioralPred) -> bool {
    match pred {
        BehavioralPred::AcMatch { .. } => true,
        BehavioralPred::Quantified { body, .. } | BehavioralPred::Not(body) => {
            pred_has_structural_component(body)
        },
        BehavioralPred::And(left, right)
        | BehavioralPred::Or(left, right)
        | BehavioralPred::Implies(left, right) => {
            pred_has_structural_component(left) || pred_has_structural_component(right)
        },
        BehavioralPred::RelationQuery { .. } | BehavioralPred::Top => false,
    }
}

fn guard_pred_obligation_kind(pred: &BehavioralPred) -> RhoGuardObligationKind {
    if pred_has_structural_component(pred) {
        RhoGuardObligationKind::StructuralPattern
    } else {
        RhoGuardObligationKind::BehavioralPredicate
    }
}

fn collect_term_guard_obligations(rule: &GrammarRule, out: &mut BTreeSet<RhoGuardObligation>) {
    fn walk_params(label: &str, params: &[TermParam], out: &mut BTreeSet<RhoGuardObligation>) {
        for param in params {
            match param {
                TermParam::GuardBody { name } => {
                    out.insert(RhoGuardObligation::new(
                        format!("term:{label}:guard:{name}"),
                        RhoGuardObligationKind::BehavioralPredicate,
                    ));
                },
                TermParam::Optional { params } => walk_params(label, params, out),
                TermParam::Simple { .. }
                | TermParam::Abstraction { .. }
                | TermParam::MultiAbstraction { .. } => {},
            }
        }
    }

    if let Some(params) = rule.term_context.as_ref() {
        walk_params(&rule.label.to_string(), params, out);
    }
}

fn collect_premise_guard_obligations(
    owner_kind: &str,
    owner_name: &str,
    premises: &[Premise],
    out: &mut BTreeSet<RhoGuardObligation>,
) {
    fn walk(
        owner_kind: &str,
        owner_name: &str,
        premise: &Premise,
        index: usize,
        out: &mut BTreeSet<RhoGuardObligation>,
    ) {
        match premise {
            Premise::BehavioralGuard(pred) => {
                out.insert(RhoGuardObligation::new(
                    format!("{owner_kind}:{owner_name}:guard:{index}"),
                    guard_pred_obligation_kind(pred),
                ));
            },
            Premise::ForAll { body, .. } => walk(owner_kind, owner_name, body, index, out),
            Premise::Freshness(_)
            | Premise::Congruence { .. }
            | Premise::RelationQuery { .. }
            | Premise::SyntheticInjGuard { .. } => {},
        }
    }

    for (index, premise) in premises.iter().enumerate() {
        walk(owner_kind, owner_name, premise, index, out);
    }
}

fn collect_rewrite_guard_obligations(
    rewrite: &RewriteRule,
    out: &mut BTreeSet<RhoGuardObligation>,
) {
    collect_premise_guard_obligations("rewrite", &rewrite.name.to_string(), &rewrite.premises, out);
}

fn collect_guard_config_obligations(
    guard_config: &GuardConfig,
    out: &mut BTreeSet<RhoGuardObligation>,
) {
    match guard_config.builtin_predicates.as_ref() {
        Some(predicates) => {
            for predicate in predicates {
                out.insert(RhoGuardObligation::new(
                    format!("predicate:{}", predicate.name),
                    RhoGuardObligationKind::BehavioralPredicate,
                ));
            }
        },
        None => {
            out.insert(RhoGuardObligation::new(
                "predicate:standard-builtins",
                RhoGuardObligationKind::BehavioralPredicate,
            ));
        },
    }

    for theory in &guard_config.theories {
        out.insert(RhoGuardObligation::new(
            format!("theory:{}", theory.name),
            RhoGuardObligationKind::TheoryRegistration,
        ));
    }

    if let Some(channels) = guard_config.channels.as_ref() {
        for channel in &channels.channel_categories {
            out.insert(RhoGuardObligation::new(
                format!("channel:{}", channel.category),
                RhoGuardObligationKind::RhoNativeJoin,
            ));
        }
        for join in &channels.join_patterns {
            out.insert(RhoGuardObligation::new(
                format!("join:{}", join.label),
                RhoGuardObligationKind::RhoNativeJoin,
            ));
        }
    }
}

/// Collect the exact guard/predicated-type obligation set induced by a
/// `LanguageDef`.
pub fn collect_guard_obligations(def: &LanguageDef) -> Vec<RhoGuardObligation> {
    let mut obligations = BTreeSet::new();

    if let Some(guard_config) = def.guard_config.as_ref() {
        collect_guard_config_obligations(guard_config, &mut obligations);
    }

    for rule in &def.terms {
        collect_term_guard_obligations(rule, &mut obligations);
    }
    for equation in &def.equations {
        collect_premise_guard_obligations(
            "equation",
            &equation.name.to_string(),
            &equation.premises,
            &mut obligations,
        );
    }
    for rewrite in &def.rewrites {
        collect_rewrite_guard_obligations(rewrite, &mut obligations);
    }

    obligations.into_iter().collect()
}

/// Coverage for one rule that `lower_language_def` recorded as
/// rejected by this scalar lowering family.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RhoRejectedRuleDisposition {
    pub rule: String,
    pub kind: RhoRejectedRuleDispositionKind,
}

impl RhoRejectedRuleDisposition {
    pub fn new(rule: impl Into<String>, kind: RhoRejectedRuleDispositionKind) -> Self {
        Self { rule: rule.into(), kind }
    }
}

/// Why the planner suggested a disposition for a rejected rule.
///
/// These reasons are derived from the parsed `LanguageDef`; they are not a
/// replacement for verification. A suggestion helps generated tooling avoid
/// brittle hard-coded category lists, while the default-backend gate still
/// requires exact coverage through [`RhoCoverageEvidence`].
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum RhoRejectedRuleClassificationReason {
    /// The rule carries user Rust evaluation code or an explicit HOL fold/step
    /// mode, so it belongs behind a verified native handler boundary.
    NativeEvaluation,
    /// The rejected constructor is mentioned by an equation or rewrite pattern,
    /// so it participates in non-scalar source semantics that need a Rho AST
    /// contract rather than scalar expression lowering.
    ReferencedByEquationOrRewrite,
    /// The rule contains binding, higher-order, collection, optional, guard, or
    /// syntax-operation structure that cannot be represented as one scalar
    /// Rholang expression contract.
    StructuredSyntax,
    /// The rule has scalar-operator shape but no exact scalar Rholang
    /// expression lowering. A host/runtime contract may still cover it.
    UnsupportedScalarOperator,
    /// The rule is a plain constructor outside the scalar-expression lowering
    /// subset. It is a candidate for generated Rho AST structural handling.
    StructuralConstructor,
    /// The rejected label did not correspond to a `LanguageDef::terms` rule.
    /// This should not happen for `lower_language_def`, but keeping it explicit
    /// makes stale lowering data visible to callers.
    MissingLanguageRule,
}

/// Advisory, `LanguageDef`-derived classification for a rule rejected by the
/// scalar lowering family.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RhoRejectedRuleClassification {
    pub rule: String,
    pub suggested_kind: Option<RhoRejectedRuleDispositionKind>,
    pub reason: RhoRejectedRuleClassificationReason,
}

impl RhoRejectedRuleClassification {
    fn new(
        rule: impl Into<String>,
        suggested_kind: Option<RhoRejectedRuleDispositionKind>,
        reason: RhoRejectedRuleClassificationReason,
    ) -> Self {
        Self {
            rule: rule.into(),
            suggested_kind,
            reason,
        }
    }

    /// This helper deliberately refuses classifications without a suggested
    /// kind; callers must inspect those cases instead of silently fabricating a
    /// coverage claim.
    pub fn to_disposition(&self) -> Option<RhoRejectedRuleDisposition> {
        self.suggested_kind
            .map(|kind| RhoRejectedRuleDisposition::new(self.rule.clone(), kind))
    }
}

/// Invalid rejected-rule coverage diagnostics.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum RhoRejectedRuleDispositionDiagnostic {
    MissingRuleId,
    DuplicateRuleDisposition { rule: String },
}

/// Coverage evidence for rules not lowered by the scalar Rho AST generator.
///
/// A default Rho backend may not ignore `RhoLowering::rejected`. Either every
/// rule lowered to Rholang AST, or every rejected rule is covered by an
/// explicit external/native/Rho handler contract that passed the separate
/// coverage audit.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum RhoCoverageEvidence {
    /// The backend is acceptable only when `RhoLowering::rejected` is empty.
    AllRulesLowered,
    /// Rejected rules are acceptable only when these dispositions
    /// name exactly the rejected rule set and every disposition is well-formed.
    CoveredRejectedRules(Vec<RhoRejectedRuleDisposition>),
}

impl RhoCoverageEvidence {
    fn covered_dispositions(&self) -> &[RhoRejectedRuleDisposition] {
        match self {
            Self::AllRulesLowered => &[],
            Self::CoveredRejectedRules(dispositions) => dispositions,
        }
    }

    fn covered_set(&self) -> BTreeSet<&str> {
        match self {
            Self::AllRulesLowered => BTreeSet::new(),
            Self::CoveredRejectedRules(dispositions) => dispositions
                .iter()
                .map(|disposition| disposition.rule.as_str())
                .collect(),
        }
    }

    fn uncovered_rejections(&self, lowering: &RhoLowering) -> Vec<String> {
        let covered = self.covered_set();
        lowering
            .rejected
            .iter()
            .filter(|rule| !covered.contains(rule.as_str()))
            .cloned()
            .collect()
    }

    fn extraneous_dispositions(&self, lowering: &RhoLowering) -> Vec<String> {
        let rejected: BTreeSet<&str> = lowering.rejected.iter().map(String::as_str).collect();
        self.covered_set()
            .into_iter()
            .filter(|rule| !rejected.contains(rule))
            .map(ToOwned::to_owned)
            .collect()
    }

    fn invalid_dispositions(&self) -> Vec<RhoRejectedRuleDispositionDiagnostic> {
        let mut diagnostics = Vec::new();
        let mut seen = BTreeSet::new();
        let mut duplicate_reported = BTreeSet::new();

        for disposition in self.covered_dispositions() {
            if disposition.rule.trim().is_empty() {
                diagnostics.push(RhoRejectedRuleDispositionDiagnostic::MissingRuleId);
            } else if !seen.insert(disposition.rule.as_str())
                && duplicate_reported.insert(disposition.rule.as_str())
            {
                diagnostics.push(RhoRejectedRuleDispositionDiagnostic::DuplicateRuleDisposition {
                    rule: disposition.rule.clone(),
                });
            }
        }

        diagnostics
    }

    fn exactly_covers(&self, lowering: &RhoLowering) -> bool {
        self.uncovered_rejections(lowering).is_empty()
            && self.extraneous_dispositions(lowering).is_empty()
            && self.invalid_dispositions().is_empty()
    }

    fn accepted_dispositions(&self) -> Vec<RhoRejectedRuleDisposition> {
        match self {
            Self::AllRulesLowered => Vec::new(),
            Self::CoveredRejectedRules(dispositions) => dispositions.clone(),
        }
    }
}

fn collect_referenced_constructor_labels(def: &LanguageDef) -> HashSet<String> {
    let mut labels = HashSet::new();
    for equation in &def.equations {
        equation.left.collect_constructor_labels(&mut labels);
        equation.right.collect_constructor_labels(&mut labels);
    }
    for rewrite in &def.rewrites {
        rewrite.left.collect_constructor_labels(&mut labels);
        rewrite.right.collect_constructor_labels(&mut labels);
    }
    labels
}

fn type_expr_is_structured(ty: &TypeExpr) -> bool {
    match ty {
        TypeExpr::Base(_) => false,
        TypeExpr::Arrow { .. }
        | TypeExpr::MultiBinder(_)
        | TypeExpr::Collection { .. }
        | TypeExpr::Refined { .. }
        | TypeExpr::Map { .. } => true,
    }
}

fn term_param_is_structured(param: &TermParam) -> bool {
    match param {
        TermParam::Simple { ty, .. } => type_expr_is_structured(ty),
        TermParam::Abstraction { .. }
        | TermParam::MultiAbstraction { .. }
        | TermParam::GuardBody { .. }
        | TermParam::Optional { .. } => true,
    }
}

fn grammar_item_is_structured(item: &GrammarItem) -> bool {
    matches!(item, GrammarItem::Binder { .. } | GrammarItem::Collection { .. })
}

fn syntax_expr_is_structured(expr: &SyntaxExpr) -> bool {
    matches!(expr, SyntaxExpr::Op(_))
}

fn rule_has_structured_syntax(rule: &GrammarRule) -> bool {
    rule.items.iter().any(grammar_item_is_structured)
        || rule
            .term_context
            .as_ref()
            .is_some_and(|params| params.iter().any(term_param_is_structured))
        || rule
            .syntax_pattern
            .as_ref()
            .is_some_and(|pattern| pattern.iter().any(syntax_expr_is_structured))
}

fn rule_has_scalar_operator_shape(rule: &GrammarRule) -> bool {
    let Some(pattern) = &rule.syntax_pattern else {
        return false;
    };
    matches!(
        pattern.as_slice(),
        [SyntaxExpr::Param(_), SyntaxExpr::Literal(_), SyntaxExpr::Param(_)]
            | [SyntaxExpr::Literal(_), SyntaxExpr::Param(_)]
    )
}

fn classify_rejected_rule(
    rule: &GrammarRule,
    referenced_labels: &HashSet<String>,
) -> RhoRejectedRuleClassification {
    let label = rule.label.to_string();
    if rule.rust_code.is_some() || rule.eval_mode.is_some() {
        return RhoRejectedRuleClassification::new(
            label,
            Some(RhoRejectedRuleDispositionKind::NativeHandler),
            RhoRejectedRuleClassificationReason::NativeEvaluation,
        );
    }

    if referenced_labels.contains(&label) {
        return RhoRejectedRuleClassification::new(
            label,
            Some(RhoRejectedRuleDispositionKind::RhoAstContract),
            RhoRejectedRuleClassificationReason::ReferencedByEquationOrRewrite,
        );
    }

    if rule_has_structured_syntax(rule) {
        return RhoRejectedRuleClassification::new(
            label,
            Some(RhoRejectedRuleDispositionKind::RhoAstContract),
            RhoRejectedRuleClassificationReason::StructuredSyntax,
        );
    }

    if rule_has_scalar_operator_shape(rule) {
        return RhoRejectedRuleClassification::new(
            label,
            Some(RhoRejectedRuleDispositionKind::ExternalContract),
            RhoRejectedRuleClassificationReason::UnsupportedScalarOperator,
        );
    }

    RhoRejectedRuleClassification::new(
        label,
        Some(RhoRejectedRuleDispositionKind::RhoAstContract),
        RhoRejectedRuleClassificationReason::StructuralConstructor,
    )
}

/// Classify every rule label in `lowering.rejected` using `def` as the source
/// of truth.
///
/// The returned classifications are advisory. They are intended for generated
/// coverage tooling and review output, not for bypassing the exact
/// `CoveredRejectedRules` gate. To become accepted coverage, each suggested
/// classification still has to be supplied through
/// [`RhoCoverageEvidence::CoveredRejectedRules`].
pub fn classify_rejected_rules(
    def: &LanguageDef,
    lowering: &RhoLowering,
) -> Vec<RhoRejectedRuleClassification> {
    let rules_by_label = def
        .terms
        .iter()
        .map(|rule| (rule.label.to_string(), rule))
        .collect::<HashMap<_, _>>();
    let referenced_labels = collect_referenced_constructor_labels(def);

    lowering
        .rejected
        .iter()
        .map(|label| {
            rules_by_label.get(label).map_or_else(
                || {
                    RhoRejectedRuleClassification::new(
                        label.clone(),
                        None,
                        RhoRejectedRuleClassificationReason::MissingLanguageRule,
                    )
                },
                |rule| classify_rejected_rule(rule, &referenced_labels),
            )
        })
        .collect()
}

/// Checkable inputs for selecting Rho as a language's default runtime backend.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RhoDefaultBackendRequirements {
    pub coverage: RhoCoverageEvidence,
    pub guard_coverage: RhoGuardCoverageEvidence,
}

/// Concrete plan for a language that passed the Rho-default flip gate.
#[derive(Debug, Clone, PartialEq)]
pub struct RhoDefaultBackendPlan {
    pub lowering: RhoLowering,
    pub validated_program: ValidatedRhoProgram,
    pub rejected_rule_dispositions: Vec<RhoRejectedRuleDisposition>,
    pub guard_obligation_dispositions: Vec<RhoGuardDisposition>,
}

impl RhoDefaultBackendPlan {
    /// Name of the `LanguageDef` whose lowering passed the default-backend
    /// gate. Runtime wrappers use this to reject cross-language plan
    /// installation.
    pub fn language_name(&self) -> &str {
        self.lowering.language_name()
    }

    /// Stable compiler-facing identity of the `LanguageDef` whose lowering
    /// passed the default-backend gate.
    pub fn definition_fingerprint(&self) -> &str {
        self.lowering.definition_fingerprint()
    }

    /// Executable Rho backend artifact selected and validated by the flip gate.
    pub fn program(&self) -> &ValidatedRhoProgram {
        &self.validated_program
    }

    /// Normalized AST to inject into the host Rho runtime, when available.
    pub fn ast_par(&self) -> Option<&Par> {
        self.program().ast_par()
    }

    /// Reader/debug annotation. This text is not parsed as the execution path.
    pub fn text_annotation(&self) -> &str {
        self.program().text_annotation()
    }
}

/// Rejected Rho-default plan with complete diagnostic state for callers.
#[derive(Debug, Clone, PartialEq)]
pub struct RhoDefaultBackendPlanError {
    pub lowering: Box<RhoLowering>,
    pub decision: Box<RhoFlipDecision>,
    pub uncovered_rejections: Box<[String]>,
    pub extraneous_dispositions: Box<[String]>,
    pub invalid_dispositions: Box<[RhoRejectedRuleDispositionDiagnostic]>,
    pub uncovered_guard_obligations: Box<[String]>,
    pub extraneous_guard_dispositions: Box<[String]>,
    pub invalid_guard_dispositions: Box<[RhoGuardDispositionDiagnostic]>,
    pub validation_errors: Box<[RhoValidationError]>,
}

/// Lower `def` and build the Rho-default backend plan if every flip gate passes.
pub fn plan_rho_default_backend(
    def: &LanguageDef,
    requirements: RhoDefaultBackendRequirements,
) -> Result<RhoDefaultBackendPlan, RhoDefaultBackendPlanError> {
    let lowering = lower_language_def(def);
    let validated_program = ValidatedRhoProgram::try_from(lowering.program.clone());
    let validation_errors = validated_program.clone().err().unwrap_or_default();
    let uncovered_rejections = requirements.coverage.uncovered_rejections(&lowering);
    let extraneous_dispositions = requirements.coverage.extraneous_dispositions(&lowering);
    let invalid_dispositions = requirements.coverage.invalid_dispositions();
    let guard_obligations = collect_guard_obligations(def);
    let uncovered_guard_obligations = requirements
        .guard_coverage
        .uncovered_obligations(&guard_obligations);
    let extraneous_guard_dispositions = requirements
        .guard_coverage
        .extraneous_dispositions(&guard_obligations);
    let invalid_guard_dispositions = requirements
        .guard_coverage
        .invalid_dispositions(&guard_obligations);
    let coverage_passed = requirements.coverage.exactly_covers(&lowering)
        && requirements
            .guard_coverage
            .exactly_covers(&guard_obligations);

    // Formal model: `formal/rocq/rho_bridge/theories/RhoBackendFlipGate.v`.
    // The Rust plan carries only the semantic gate result and validated
    // artifacts; proof attribution stays in comments and CI/docs, not runtime
    // data.
    let decision = decide_rho_flip(
        RhoFlipGates {
            coverage_passed,
            artifact_validated: validation_errors.is_empty(),
        },
        &lowering.deadlock_report,
    );

    if decision.can_flip_to_rho() {
        let validated_program =
            validated_program.expect("flip decision requires successful artifact validation");
        let rejected_rule_dispositions = requirements.coverage.accepted_dispositions();
        let guard_obligation_dispositions = requirements.guard_coverage.accepted_dispositions();
        Ok(RhoDefaultBackendPlan {
            rejected_rule_dispositions,
            guard_obligation_dispositions,
            validated_program,
            lowering,
        })
    } else {
        Err(RhoDefaultBackendPlanError {
            lowering: Box::new(lowering),
            decision: Box::new(decision),
            uncovered_rejections: uncovered_rejections.into_boxed_slice(),
            extraneous_dispositions: extraneous_dispositions.into_boxed_slice(),
            invalid_dispositions: invalid_dispositions.into_boxed_slice(),
            uncovered_guard_obligations: uncovered_guard_obligations.into_boxed_slice(),
            extraneous_guard_dispositions: extraneous_guard_dispositions.into_boxed_slice(),
            invalid_guard_dispositions: invalid_guard_dispositions.into_boxed_slice(),
            validation_errors: validation_errors.into_boxed_slice(),
        })
    }
}

