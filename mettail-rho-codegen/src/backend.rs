//! Rho-default backend planning.
//!
//! `RhoBackendFlipGate.v` proves the Boolean gate. This module is the Rust-side
//! artifact that a runtime selector can consume: it lowers a `LanguageDef`,
//! checks proof/oracle/coverage/artifact-validation/scheduler-fairness/deadlock
//! evidence, and either returns a concrete Rho-default backend plan or all
//! blockers.

use std::collections::{BTreeSet, HashMap, HashSet};
use std::path::{Component, Path, PathBuf};

use mettail_ast::grammar::{GrammarItem, GrammarRule, SyntaxExpr, TermParam};
use mettail_ast::language::LanguageDef;
use mettail_ast::types::TypeExpr;
use models::rhoapi::Par;

use crate::flip::{decide_rho_flip, RhoFlipDecision, RhoFlipGates};
use crate::lower::{lower_language_def, RhoLowering};
use crate::validate::{RhoValidationError, ValidatedRhoProgram};

/// Runtime disposition kind for a rule not lowered by the scalar Rho AST
/// generator.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum RhoRejectedRuleDispositionKind {
    /// Covered by a verified native system process or host-side handler.
    NativeHandler,
    /// Covered by a verified external contract supplied by the host runtime.
    ExternalContract,
    /// Covered by a non-scalar Rho AST contract generated by another lowering.
    RhoAstContract,
}

/// Auditable coverage for one rule that `lower_language_def` recorded as
/// rejected by this scalar lowering family.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RhoRejectedRuleDisposition {
    pub rule: String,
    pub kind: RhoRejectedRuleDispositionKind,
    /// Stable reference to the proof/oracle/contract artifact that justifies
    /// the disposition. Empty or whitespace-only references are rejected.
    pub evidence_ref: String,
}

impl RhoRejectedRuleDisposition {
    pub fn new(
        rule: impl Into<String>,
        kind: RhoRejectedRuleDispositionKind,
        evidence_ref: impl Into<String>,
    ) -> Self {
        Self {
            rule: rule.into(),
            kind,
            evidence_ref: evidence_ref.into(),
        }
    }
}

/// Why the planner suggested a disposition for a rejected rule.
///
/// These reasons are derived from the parsed `LanguageDef`; they are not a
/// replacement for evidence references. A suggestion helps generated tooling
/// avoid brittle hard-coded category lists, while the default-backend gate
/// still requires auditable coverage through [`RhoCoverageEvidence`].
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum RhoRejectedRuleClassificationReason {
    /// The rule carries user Rust evaluation code or an explicit HOL fold/step
    /// mode, so it belongs behind a verified native handler boundary.
    NativeEvaluation,
    /// The rejected constructor is mentioned by an equation or rewrite pattern,
    /// so it participates in non-scalar source semantics that need a Rho AST
    /// contract rather than scalar expression lowering.
    ReferencedByEquationOrRewrite,
    /// The rule contains binding, higher-order, collection, optional, guard, or
    /// syntax-operation structure that cannot be represented as one scalar
    /// Rholang expression contract.
    StructuredSyntax,
    /// The rule has scalar-operator shape but no exact scalar Rholang
    /// expression lowering. A host/runtime contract may still cover it.
    UnsupportedScalarOperator,
    /// The rule is a plain constructor outside the scalar-expression lowering
    /// subset. It is a candidate for generated Rho AST structural handling.
    StructuralConstructor,
    /// The rejected label did not correspond to a `LanguageDef::terms` rule.
    /// This should not happen for `lower_language_def`, but keeping it explicit
    /// makes stale lowering data visible to callers.
    MissingLanguageRule,
}

/// Advisory, `LanguageDef`-derived classification for a rule rejected by the
/// scalar lowering family.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RhoRejectedRuleClassification {
    pub rule: String,
    pub suggested_kind: Option<RhoRejectedRuleDispositionKind>,
    pub reason: RhoRejectedRuleClassificationReason,
}

impl RhoRejectedRuleClassification {
    fn new(
        rule: impl Into<String>,
        suggested_kind: Option<RhoRejectedRuleDispositionKind>,
        reason: RhoRejectedRuleClassificationReason,
    ) -> Self {
        Self {
            rule: rule.into(),
            suggested_kind,
            reason,
        }
    }

    /// Convert an advisory classification into an auditable disposition by
    /// pairing it with an explicit evidence reference.
    ///
    /// This helper deliberately refuses classifications without a suggested
    /// kind; callers must inspect those cases instead of silently fabricating a
    /// coverage claim.
    pub fn to_disposition(
        &self,
        evidence_ref: impl Into<String>,
    ) -> Option<RhoRejectedRuleDisposition> {
        self.suggested_kind.map(|kind| {
            RhoRejectedRuleDisposition::new(self.rule.clone(), kind, evidence_ref.into())
        })
    }
}

/// Invalid rejected-rule coverage diagnostics.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum RhoRejectedRuleDispositionDiagnostic {
    MissingRuleId,
    MissingEvidenceRef { rule: String },
    DuplicateRuleDisposition { rule: String },
}

/// Coverage evidence for rules not lowered by the scalar Rho AST generator.
///
/// A default Rho backend may not ignore `RhoLowering::rejected`. Either every
/// rule lowered to Rholang AST, or every rejected rule is covered by an
/// explicit external/native/Rho handler contract that passed the separate
/// coverage audit.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum RhoCoverageEvidence {
    /// The backend is acceptable only when `RhoLowering::rejected` is empty.
    AllRulesLowered,
    /// Rejected rules are acceptable only when these auditable dispositions
    /// name exactly the rejected rule set and every disposition is well-formed.
    CoveredRejectedRules(Vec<RhoRejectedRuleDisposition>),
}

impl RhoCoverageEvidence {
    fn covered_dispositions(&self) -> &[RhoRejectedRuleDisposition] {
        match self {
            Self::AllRulesLowered => &[],
            Self::CoveredRejectedRules(dispositions) => dispositions,
        }
    }

    fn covered_set(&self) -> BTreeSet<&str> {
        match self {
            Self::AllRulesLowered => BTreeSet::new(),
            Self::CoveredRejectedRules(dispositions) => dispositions
                .iter()
                .map(|disposition| disposition.rule.as_str())
                .collect(),
        }
    }

    fn uncovered_rejections(&self, lowering: &RhoLowering) -> Vec<String> {
        let covered = self.covered_set();
        lowering
            .rejected
            .iter()
            .filter(|rule| !covered.contains(rule.as_str()))
            .cloned()
            .collect()
    }

    fn extraneous_dispositions(&self, lowering: &RhoLowering) -> Vec<String> {
        let rejected: BTreeSet<&str> = lowering.rejected.iter().map(String::as_str).collect();
        self.covered_set()
            .into_iter()
            .filter(|rule| !rejected.contains(rule))
            .map(ToOwned::to_owned)
            .collect()
    }

    fn invalid_dispositions(&self) -> Vec<RhoRejectedRuleDispositionDiagnostic> {
        let mut diagnostics = Vec::new();
        let mut seen = BTreeSet::new();
        let mut duplicate_reported = BTreeSet::new();

        for disposition in self.covered_dispositions() {
            if disposition.rule.trim().is_empty() {
                diagnostics.push(RhoRejectedRuleDispositionDiagnostic::MissingRuleId);
            } else if !seen.insert(disposition.rule.as_str())
                && duplicate_reported.insert(disposition.rule.as_str())
            {
                diagnostics.push(RhoRejectedRuleDispositionDiagnostic::DuplicateRuleDisposition {
                    rule: disposition.rule.clone(),
                });
            }

            if disposition.evidence_ref.trim().is_empty() {
                diagnostics.push(RhoRejectedRuleDispositionDiagnostic::MissingEvidenceRef {
                    rule: disposition.rule.clone(),
                });
            }
        }

        diagnostics
    }

    fn exactly_covers(&self, lowering: &RhoLowering) -> bool {
        self.uncovered_rejections(lowering).is_empty()
            && self.extraneous_dispositions(lowering).is_empty()
            && self.invalid_dispositions().is_empty()
    }

    fn accepted_dispositions(&self) -> Vec<RhoRejectedRuleDisposition> {
        match self {
            Self::AllRulesLowered => Vec::new(),
            Self::CoveredRejectedRules(dispositions) => dispositions.clone(),
        }
    }
}

fn collect_referenced_constructor_labels(def: &LanguageDef) -> HashSet<String> {
    let mut labels = HashSet::new();
    for equation in &def.equations {
        equation.left.collect_constructor_labels(&mut labels);
        equation.right.collect_constructor_labels(&mut labels);
    }
    for rewrite in &def.rewrites {
        rewrite.left.collect_constructor_labels(&mut labels);
        rewrite.right.collect_constructor_labels(&mut labels);
    }
    labels
}

fn type_expr_is_structured(ty: &TypeExpr) -> bool {
    match ty {
        TypeExpr::Base(_) => false,
        TypeExpr::Arrow { .. }
        | TypeExpr::MultiBinder(_)
        | TypeExpr::Collection { .. }
        | TypeExpr::Refined { .. }
        | TypeExpr::Map { .. } => true,
    }
}

fn term_param_is_structured(param: &TermParam) -> bool {
    match param {
        TermParam::Simple { ty, .. } => type_expr_is_structured(ty),
        TermParam::Abstraction { .. }
        | TermParam::MultiAbstraction { .. }
        | TermParam::GuardBody { .. }
        | TermParam::Optional { .. } => true,
    }
}

fn grammar_item_is_structured(item: &GrammarItem) -> bool {
    matches!(item, GrammarItem::Binder { .. } | GrammarItem::Collection { .. })
}

fn syntax_expr_is_structured(expr: &SyntaxExpr) -> bool {
    matches!(expr, SyntaxExpr::Op(_))
}

fn rule_has_structured_syntax(rule: &GrammarRule) -> bool {
    rule.items.iter().any(grammar_item_is_structured)
        || rule
            .term_context
            .as_ref()
            .is_some_and(|params| params.iter().any(term_param_is_structured))
        || rule
            .syntax_pattern
            .as_ref()
            .is_some_and(|pattern| pattern.iter().any(syntax_expr_is_structured))
}

fn rule_has_scalar_operator_shape(rule: &GrammarRule) -> bool {
    let Some(pattern) = &rule.syntax_pattern else {
        return false;
    };
    matches!(
        pattern.as_slice(),
        [SyntaxExpr::Param(_), SyntaxExpr::Literal(_), SyntaxExpr::Param(_)]
            | [SyntaxExpr::Literal(_), SyntaxExpr::Param(_)]
    )
}

fn classify_rejected_rule(
    rule: &GrammarRule,
    referenced_labels: &HashSet<String>,
) -> RhoRejectedRuleClassification {
    let label = rule.label.to_string();
    if rule.rust_code.is_some() || rule.eval_mode.is_some() {
        return RhoRejectedRuleClassification::new(
            label,
            Some(RhoRejectedRuleDispositionKind::NativeHandler),
            RhoRejectedRuleClassificationReason::NativeEvaluation,
        );
    }

    if referenced_labels.contains(&label) {
        return RhoRejectedRuleClassification::new(
            label,
            Some(RhoRejectedRuleDispositionKind::RhoAstContract),
            RhoRejectedRuleClassificationReason::ReferencedByEquationOrRewrite,
        );
    }

    if rule_has_structured_syntax(rule) {
        return RhoRejectedRuleClassification::new(
            label,
            Some(RhoRejectedRuleDispositionKind::RhoAstContract),
            RhoRejectedRuleClassificationReason::StructuredSyntax,
        );
    }

    if rule_has_scalar_operator_shape(rule) {
        return RhoRejectedRuleClassification::new(
            label,
            Some(RhoRejectedRuleDispositionKind::ExternalContract),
            RhoRejectedRuleClassificationReason::UnsupportedScalarOperator,
        );
    }

    RhoRejectedRuleClassification::new(
        label,
        Some(RhoRejectedRuleDispositionKind::RhoAstContract),
        RhoRejectedRuleClassificationReason::StructuralConstructor,
    )
}

/// Classify every rule label in `lowering.rejected` using `def` as the source
/// of truth.
///
/// The returned classifications are advisory. They are intended for generated
/// coverage tooling and review output, not for bypassing the exact
/// `CoveredRejectedRules` gate. To become accepted coverage, each suggested
/// classification still has to be paired with a stable evidence reference and
/// supplied through [`RhoCoverageEvidence::CoveredRejectedRules`].
pub fn classify_rejected_rules(
    def: &LanguageDef,
    lowering: &RhoLowering,
) -> Vec<RhoRejectedRuleClassification> {
    let rules_by_label = def
        .terms
        .iter()
        .map(|rule| (rule.label.to_string(), rule))
        .collect::<HashMap<_, _>>();
    let referenced_labels = collect_referenced_constructor_labels(def);

    lowering
        .rejected
        .iter()
        .map(|label| {
            rules_by_label.get(label).map_or_else(
                || {
                    RhoRejectedRuleClassification::new(
                        label.clone(),
                        None,
                        RhoRejectedRuleClassificationReason::MissingLanguageRule,
                    )
                },
                |rule| classify_rejected_rule(rule, &referenced_labels),
            )
        })
        .collect()
}

/// Evidence inputs for selecting Rho as a language's default runtime backend.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RhoDefaultBackendEvidence {
    pub proofs_passed: bool,
    pub proof_evidence_refs: Vec<String>,
    pub oracle_parity_passed: bool,
    pub oracle_parity_evidence_refs: Vec<String>,
    pub coverage_audit_passed: bool,
    pub coverage_audit_evidence_refs: Vec<String>,
    pub scheduler_fairness_passed: bool,
    pub scheduler_fairness_evidence_refs: Vec<String>,
    pub coverage: RhoCoverageEvidence,
}

/// Named evidence gate whose positive result must be backed by stable
/// references before a Rho-default backend plan can be emitted.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum RhoDefaultBackendEvidenceGate {
    Proofs,
    OracleParity,
    CoverageAudit,
    SchedulerFairness,
}

/// Evidence-reference hygiene diagnostics for the Rust image of the flip gate.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum RhoGateEvidenceDiagnostic {
    MissingEvidenceRefs { gate: RhoDefaultBackendEvidenceGate },
    BlankEvidenceRef { gate: RhoDefaultBackendEvidenceGate },
}

/// Evidence-reference audit policy for production Rho-default planning.
///
/// The ordinary flip gate checks that positive external gates carry stable,
/// nonblank evidence references. This policy strengthens that boundary for
/// production callers: repository-relative references must resolve to existing
/// local artifacts, and logical evidence identifiers must use an explicitly
/// allowed prefix.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RhoEvidenceRefAuditPolicy {
    repo_root: PathBuf,
    allowed_logical_prefixes: BTreeSet<String>,
}

impl RhoEvidenceRefAuditPolicy {
    /// Build a strict local-artifact audit rooted at the repository. Logical
    /// evidence identifiers are rejected unless their prefix is explicitly
    /// allowed with [`Self::with_allowed_logical_prefix`].
    pub fn new(repo_root: impl Into<PathBuf>) -> Self {
        Self {
            repo_root: repo_root.into(),
            allowed_logical_prefixes: BTreeSet::new(),
        }
    }

    /// Permit a non-file evidence namespace such as
    /// `mettail-rho-codegen:artifact-validation` or `native-handler:Rule`.
    pub fn with_allowed_logical_prefix(mut self, prefix: impl Into<String>) -> Self {
        self.allowed_logical_prefixes.insert(prefix.into());
        self
    }

    pub fn repo_root(&self) -> &Path {
        &self.repo_root
    }

    pub fn allowed_logical_prefixes(&self) -> &BTreeSet<String> {
        &self.allowed_logical_prefixes
    }
}

/// Evidence-reference audit diagnostics surfaced by the strict production
/// planner.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum RhoEvidenceRefAuditDiagnostic {
    AbsoluteLocalPath {
        evidence_ref: String,
    },
    ParentComponent {
        evidence_ref: String,
    },
    MissingLocalPath {
        evidence_ref: String,
        resolved_path: String,
    },
    DisallowedLogicalRef {
        evidence_ref: String,
        prefix: String,
    },
    MissingLogicalPrefix {
        evidence_ref: String,
    },
}

/// Concrete plan for a language that passed the Rho-default flip gate.
#[derive(Debug, Clone, PartialEq)]
pub struct RhoDefaultBackendPlan {
    pub lowering: RhoLowering,
    pub validated_program: ValidatedRhoProgram,
    pub rejected_rule_dispositions: Vec<RhoRejectedRuleDisposition>,
    pub evidence_refs: Vec<String>,
}

impl RhoDefaultBackendPlan {
    /// Name of the `LanguageDef` whose lowering passed the default-backend
    /// gate. Runtime wrappers use this to reject cross-language plan
    /// installation.
    pub fn language_name(&self) -> &str {
        self.lowering.language_name()
    }

    /// Executable Rho backend artifact selected and validated by the flip gate.
    pub fn program(&self) -> &ValidatedRhoProgram {
        &self.validated_program
    }

    /// Normalized AST to inject into the host Rho runtime, when available.
    pub fn ast_par(&self) -> Option<&Par> {
        self.program().ast_par()
    }

    /// Reader/debug annotation. This text is not parsed as the execution path.
    pub fn text_annotation(&self) -> &str {
        self.program().text_annotation()
    }

    /// Stable proof, oracle, coverage, validation, scheduler-fairness,
    /// deadlock-analysis, and handler evidence references that justified
    /// exposing this plan as a default runtime backend.
    pub fn evidence_refs(&self) -> &[String] {
        &self.evidence_refs
    }
}

/// Rejected Rho-default plan with complete diagnostic state for callers.
#[derive(Debug, Clone, PartialEq)]
pub struct RhoDefaultBackendPlanError {
    pub lowering: Box<RhoLowering>,
    pub decision: Box<RhoFlipDecision>,
    pub uncovered_rejections: Box<[String]>,
    pub extraneous_dispositions: Box<[String]>,
    pub invalid_dispositions: Box<[RhoRejectedRuleDispositionDiagnostic]>,
    pub invalid_gate_evidence_refs: Box<[RhoGateEvidenceDiagnostic]>,
    pub invalid_audited_evidence_refs: Box<[RhoEvidenceRefAuditDiagnostic]>,
    pub validation_errors: Box<[RhoValidationError]>,
}

fn gate_evidence_diagnostics(
    gate: RhoDefaultBackendEvidenceGate,
    passed: bool,
    refs: &[String],
) -> Vec<RhoGateEvidenceDiagnostic> {
    let mut diagnostics = Vec::new();
    if passed && refs.is_empty() {
        diagnostics.push(RhoGateEvidenceDiagnostic::MissingEvidenceRefs { gate });
    }
    for evidence_ref in refs {
        if evidence_ref.trim().is_empty() {
            diagnostics.push(RhoGateEvidenceDiagnostic::BlankEvidenceRef { gate });
        }
    }
    diagnostics
}

fn gate_passes_with_refs(passed: bool, diagnostics: &[RhoGateEvidenceDiagnostic]) -> bool {
    passed && diagnostics.is_empty()
}

fn push_refs(out: &mut BTreeSet<String>, refs: &[String]) {
    for evidence_ref in refs {
        let trimmed = evidence_ref.trim();
        if !trimmed.is_empty() {
            out.insert(trimmed.to_string());
        }
    }
}

fn evidence_ref_logical_prefix(evidence_ref: &str) -> Option<&str> {
    let colon = evidence_ref.find(':')?;
    let slash = evidence_ref.find(['/', '\\']).unwrap_or(usize::MAX);
    (colon < slash).then_some(&evidence_ref[..colon])
}

fn audit_one_evidence_ref(
    policy: &RhoEvidenceRefAuditPolicy,
    evidence_ref: &str,
) -> Vec<RhoEvidenceRefAuditDiagnostic> {
    let trimmed = evidence_ref.trim();
    let mut diagnostics = Vec::new();

    if let Some(prefix) = evidence_ref_logical_prefix(trimmed) {
        if prefix.is_empty() {
            diagnostics.push(RhoEvidenceRefAuditDiagnostic::MissingLogicalPrefix {
                evidence_ref: trimmed.to_string(),
            });
        } else if !policy.allowed_logical_prefixes.contains(prefix) {
            diagnostics.push(RhoEvidenceRefAuditDiagnostic::DisallowedLogicalRef {
                evidence_ref: trimmed.to_string(),
                prefix: prefix.to_string(),
            });
        }
        return diagnostics;
    }

    let path = Path::new(trimmed);
    if path.is_absolute() {
        diagnostics.push(RhoEvidenceRefAuditDiagnostic::AbsoluteLocalPath {
            evidence_ref: trimmed.to_string(),
        });
        return diagnostics;
    }
    if path
        .components()
        .any(|component| component == Component::ParentDir)
    {
        diagnostics.push(RhoEvidenceRefAuditDiagnostic::ParentComponent {
            evidence_ref: trimmed.to_string(),
        });
        return diagnostics;
    }

    let resolved = policy.repo_root.join(path);
    if !resolved.exists() {
        diagnostics.push(RhoEvidenceRefAuditDiagnostic::MissingLocalPath {
            evidence_ref: trimmed.to_string(),
            resolved_path: resolved.display().to_string(),
        });
    }

    diagnostics
}

fn audit_evidence_refs(
    evidence: &RhoDefaultBackendEvidence,
    policy: Option<&RhoEvidenceRefAuditPolicy>,
) -> Vec<RhoEvidenceRefAuditDiagnostic> {
    let Some(policy) = policy else {
        return Vec::new();
    };

    evidence
        .proof_evidence_refs
        .iter()
        .chain(evidence.oracle_parity_evidence_refs.iter())
        .chain(evidence.coverage_audit_evidence_refs.iter())
        .chain(evidence.scheduler_fairness_evidence_refs.iter())
        .chain(
            evidence
                .coverage
                .covered_dispositions()
                .iter()
                .map(|disposition| &disposition.evidence_ref),
        )
        .flat_map(|evidence_ref| audit_one_evidence_ref(policy, evidence_ref))
        .collect()
}

fn accepted_evidence_refs(
    evidence: &RhoDefaultBackendEvidence,
    validated_program: &ValidatedRhoProgram,
    dispositions: &[RhoRejectedRuleDisposition],
) -> Vec<String> {
    let mut refs = BTreeSet::new();
    push_refs(&mut refs, &evidence.proof_evidence_refs);
    push_refs(&mut refs, &evidence.oracle_parity_evidence_refs);
    push_refs(&mut refs, &evidence.coverage_audit_evidence_refs);
    push_refs(&mut refs, &evidence.scheduler_fairness_evidence_refs);
    refs.insert(format!(
        "mettail-rho-codegen:artifact-validation:{:?}",
        validated_program.artifact_kind()
    ));
    refs.insert("mettail-rho-codegen:channel-deadlock-analysis:no-new-deadlocks".to_string());
    for disposition in dispositions {
        let trimmed = disposition.evidence_ref.trim();
        if !trimmed.is_empty() {
            refs.insert(trimmed.to_string());
        }
    }
    refs.into_iter().collect()
}

/// Lower `def` and build the Rho-default backend plan if every flip gate passes.
pub fn plan_rho_default_backend(
    def: &LanguageDef,
    evidence: RhoDefaultBackendEvidence,
) -> Result<RhoDefaultBackendPlan, RhoDefaultBackendPlanError> {
    plan_rho_default_backend_impl(def, evidence, None)
}

/// Lower `def` and build the Rho-default backend plan with strict evidence
/// reference auditing.
///
/// Use this entry point for production runtime flips. It preserves the same
/// proof/oracle/coverage/artifact/fairness/deadlock gate as
/// [`plan_rho_default_backend`], then additionally rejects missing local
/// evidence artifacts and unapproved logical evidence namespaces.
pub fn plan_rho_default_backend_with_evidence_audit(
    def: &LanguageDef,
    evidence: RhoDefaultBackendEvidence,
    audit_policy: &RhoEvidenceRefAuditPolicy,
) -> Result<RhoDefaultBackendPlan, RhoDefaultBackendPlanError> {
    plan_rho_default_backend_impl(def, evidence, Some(audit_policy))
}

fn plan_rho_default_backend_impl(
    def: &LanguageDef,
    evidence: RhoDefaultBackendEvidence,
    audit_policy: Option<&RhoEvidenceRefAuditPolicy>,
) -> Result<RhoDefaultBackendPlan, RhoDefaultBackendPlanError> {
    let lowering = lower_language_def(def);
    let validated_program = ValidatedRhoProgram::try_from(lowering.program.clone());
    let validation_errors = validated_program.clone().err().unwrap_or_default();
    let uncovered_rejections = evidence.coverage.uncovered_rejections(&lowering);
    let extraneous_dispositions = evidence.coverage.extraneous_dispositions(&lowering);
    let invalid_dispositions = evidence.coverage.invalid_dispositions();
    let invalid_audited_evidence_refs = audit_evidence_refs(&evidence, audit_policy);
    let proof_evidence_diagnostics = gate_evidence_diagnostics(
        RhoDefaultBackendEvidenceGate::Proofs,
        evidence.proofs_passed,
        &evidence.proof_evidence_refs,
    );
    let oracle_evidence_diagnostics = gate_evidence_diagnostics(
        RhoDefaultBackendEvidenceGate::OracleParity,
        evidence.oracle_parity_passed,
        &evidence.oracle_parity_evidence_refs,
    );
    let coverage_audit_evidence_diagnostics = gate_evidence_diagnostics(
        RhoDefaultBackendEvidenceGate::CoverageAudit,
        evidence.coverage_audit_passed,
        &evidence.coverage_audit_evidence_refs,
    );
    let scheduler_fairness_evidence_diagnostics = gate_evidence_diagnostics(
        RhoDefaultBackendEvidenceGate::SchedulerFairness,
        evidence.scheduler_fairness_passed,
        &evidence.scheduler_fairness_evidence_refs,
    );
    let invalid_gate_evidence_refs = proof_evidence_diagnostics
        .iter()
        .chain(oracle_evidence_diagnostics.iter())
        .chain(coverage_audit_evidence_diagnostics.iter())
        .chain(scheduler_fairness_evidence_diagnostics.iter())
        .cloned()
        .collect::<Vec<_>>();
    let coverage_passed =
        gate_passes_with_refs(evidence.coverage_audit_passed, &coverage_audit_evidence_diagnostics)
            && evidence.coverage.exactly_covers(&lowering);
    let decision = decide_rho_flip(
        RhoFlipGates {
            proofs_passed: gate_passes_with_refs(
                evidence.proofs_passed,
                &proof_evidence_diagnostics,
            ),
            oracle_parity_passed: gate_passes_with_refs(
                evidence.oracle_parity_passed,
                &oracle_evidence_diagnostics,
            ),
            coverage_passed,
            artifact_validated: validation_errors.is_empty(),
            scheduler_fairness_passed: gate_passes_with_refs(
                evidence.scheduler_fairness_passed,
                &scheduler_fairness_evidence_diagnostics,
            ),
        },
        &lowering.deadlock_report,
    );

    if decision.can_flip_to_rho() && invalid_audited_evidence_refs.is_empty() {
        let validated_program =
            validated_program.expect("flip decision requires successful artifact validation");
        let rejected_rule_dispositions = evidence.coverage.accepted_dispositions();
        let evidence_refs =
            accepted_evidence_refs(&evidence, &validated_program, &rejected_rule_dispositions);
        Ok(RhoDefaultBackendPlan {
            rejected_rule_dispositions,
            validated_program,
            evidence_refs,
            lowering,
        })
    } else {
        Err(RhoDefaultBackendPlanError {
            lowering: Box::new(lowering),
            decision: Box::new(decision),
            uncovered_rejections: uncovered_rejections.into_boxed_slice(),
            extraneous_dispositions: extraneous_dispositions.into_boxed_slice(),
            invalid_dispositions: invalid_dispositions.into_boxed_slice(),
            invalid_gate_evidence_refs: invalid_gate_evidence_refs.into_boxed_slice(),
            invalid_audited_evidence_refs: invalid_audited_evidence_refs.into_boxed_slice(),
            validation_errors: validation_errors.into_boxed_slice(),
        })
    }
}

